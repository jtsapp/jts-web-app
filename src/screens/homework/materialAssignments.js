// Задания с живых уроков (MaterialAssignment) на экране «Домашняя работа».
//
// Это не вторая домашка, а существующий инструмент преподавателя «задать
// материал как ДЗ» из админки. Здесь назначение приводится к форме карточки
// HomeworkList (id/title/status/dueDate/grade), чтобы жить в одном списке с
// обычными работами: у ученика одна «Домашняя работа», а не два раздела про
// одно и то же. Ни сети, ни React — под юнит-тесты.

import { isLevelTestUrl, isStandaloneLessonUrl } from '../live/catalogLessonByUrl.js'
import { engineOf } from '../live/lessonExtractor.js'

/** Оценено ли назначение преподавателем (у него нет статусной машины ДЗ). */
export function isMaterialGraded(a) {
  return a?.gradedAt != null || a?.teacherScore != null
}

/**
 * Ответил ли ученик — то есть приложил ли хоть один файл.
 *
 * У назначения нет статусной машины домашки: сдачи, возврата на доработку и
 * «на проверке» у него не бывает. Вложение и ЕСТЬ сдача — другого способа
 * сказать «я сделал» у ученика нет.
 */
export function hasAnswerFiles(a) {
  return (a?.files?.length ?? 0) > 0
}

/**
 * Обязан ли ученик приложить файл, чтобы закрыть это задание.
 *
 * Пока только выданная карточка урока: у неё нет ни проверяемых заданий, ни
 * сессии, поэтому без вложения она со сроком по умолчанию краснела бы
 * просроченной навсегда. Интерактив закрывается своей сессией и оценкой, а
 * обычный файл-материал сейчас так и живёт — расширять сюда его можно, но это
 * отдельное решение, а не побочный эффект.
 */
export function needsAnswerFile(a) {
  return isLessonCard(a)
}

/**
 * Карточка списка из назначения. id с префиксом «m-», чтобы не столкнуться с
 * числовыми id домашних работ; статусов у назначения три — заданное, сданное
 * вложением и проверенное, — а бейджи и просрочку по dueDate дальше считает
 * homeworkStateKey, как у обычной работы.
 */
export function materialCard(a) {
  return {
    id: `m-${a.id}`,
    kind: 'material',
    // Задали одну карточку урока — она и есть название задания. «Unit 3» про
    // одну карточку из тридцати не сообщает ученику ничего: он не поймёт, что
    // именно ему задали, пока не откроет урок и не пролистает его целиком.
    title: a.cardTitle || a.materialTitle,
    // Что именно задано, список выводит из самой выдачи (assignment ниже) через
    // assignmentScope — плоская копия снимка тут показывала бы и сырой текст
    // выданного блока, который ученику не показывают.
    // Статус и просрочку считает СЕРВЕР (MaterialAssignmentService.statusOf) — здесь
    // их больше не выводят. Раньше выводили: «есть вложения — значит сдана», своей
    // копией правила в каждом клиенте. Копии успели разойтись, а по работе, которая
    // решается прямо в уроке, вложений не бывает вовсе — она не становилась сданной
    // никогда.
    status: a.status,
    isOverdue: a.isOverdue,
    dueDate: a.dueDate ?? null,
    grade: a.teacherScore ?? null,
    // Преподаватель закрыл выдачу без сдачи (та же отметка, что у домашней
    // работы, spec §5.7) — без неё homeworkStateKey не отличал такую выдачу от
    // настоящей проверки, и список показывал зелёное «Проверено» тому, чей
    // ответ преподаватель не открывал.
    closedWithoutSubmission: a.closedWithoutSubmission,
    assignment: a,
  }
}

/** Интерактив открывается через render-эндпоинт (с bridge-скриптом), остальное — прямой файл. */
export function isInteractiveMaterial(a) {
  return a?.materialType === 'INTERACTIVE_HTML' || isCatalogHtmlLink(a)
}

/**
 * Урок каталога, выданный ссылкой, — тоже через render-эндпоинт, а не файлом.
 *
 * <p>Поймано на стенде: у выданного блока живого урока materialType — LINK, а не
 * INTERACTIVE_HTML, и ученик получал сырой файл в новой вкладке. Это значит: без
 * моста (ответы никуда не уходили, преподаватель не видел работу) и с начала
 * урока, без единого намёка, какой из тридцати блоков ему задали. Сервер такой
 * материал рисовать умеет давно — getRawHtmlForRender тянет ссылки своего
 * хранилища каталога и вклеивает мост с автоуказкой на выданный блок, — просто
 * клиент его об этом не спрашивал.
 *
 * <p>Эвристика МАРШРУТИЗАЦИИ, а не проверка доступа: настоящий сторож — бэкенд,
 * он тянет только адреса своего каталога (защита от SSRF), поэтому вольное
 * совпадение здесь дырой стать не может. Тот же приём и та же причина, что у
 * админки (lesson-workspace.component.ts#isCatalogHtmlLink).
 */
export function isCatalogHtmlLink(a) {
  return a?.materialType === 'LINK'
    && /\/course-catalog\/.*\.html?(?:[?#]|$)/i.test(a?.fileUrl ?? '')
}

/**
 * Назначена одна карточка живого урока, а не материал целиком.
 *
 * <p>Такое задание открывается НЕ файлом в новой вкладке, а самим уроком в
 * кабинете: у карточки бывает аудио с относительным путём и картинки из
 * словарной колоды того же урока — вне урока они не работают. Поэтому и
 * выдаётся адрес, а не снимок.
 */
export function isLessonCard(a) {
  return !!a?.cardId && a?.catalogLessonId != null
}

/** Файл урока каталога — та же примета, по которой его узнаёт живой урок (SectionMaterialFrame). */
const CATALOG_LESSON_FILE = /\/course-catalog\/.*\.html?(?:[?#]|$)/i

/**
 * Что именно задано из материала — строка под его названием: ключ словаря
 * (`{ key }`) или готовый текст сервера (`{ text }`); null — строки нет.
 *
 * <p>Снимок stageTitlesSnapshot пишет сервер (MaterialAssignmentService.resolveScope):
 * у заданий и стадий это собранные им подписи («Practice · Задание 1, …»), у
 * урока файла целиком — «Урок целиком», у простого файла снимка нет вовсе. Но
 * подпись текстового блока у файла без ключей присылает страница — это сырой
 * текст самого блока (blockText моста режет textContent до 80 символов): эмодзи,
 * слова вперемешку, обрыв на полуслове. Ученик читал под заголовком
 * «🛏 bedroom👍👎🍳 kitchen👍👎…». Такой снимок не показываем никогда: блок
 * называется «Фрагмент урока», а какой именно — видно, когда рамка открывается
 * на нём.
 *
 * <p>У карточки урока строки нет: её название (materialCard.title) уже и есть то,
 * что задано.
 *
 * <p>То же правило у преподавателя (web-admin, assignment-title.util.ts →
 * assignmentScope): что задали, обе стороны обязаны называть одинаково.
 */
export function assignmentScope(a) {
  if (!a || isLessonCard(a)) return null
  if ((a.blockKeys?.length ?? 0) > 0) return { key: 'homework.scope.fragment' }
  const snapshot = String(a.stageTitlesSnapshot ?? '').trim()
  if ((a.taskTids?.length ?? 0) > 0) return snapshot ? { text: snapshot } : { key: 'homework.scope.tasks' }
  if ((a.stageIndexes?.length ?? 0) > 0) return snapshot ? { text: snapshot } : { key: 'homework.scope.stages' }
  return snapshot ? { text: snapshot } : null
}

/**
 * Выдан конкретный кусок материала, а не он весь.
 *
 * <p>Три способа адресации, все считает сервер и присылает готовыми: блоки
 * (blockKeys), отдельные задания (taskTids) и стадии (stageIndexes). Пусто во
 * всех трёх — задан материал целиком.
 */
export function isAddressedPart(a) {
  return (a?.blockKeys?.length ?? 0) > 0
    || (a?.taskTids?.length ?? 0) > 0
    || (a?.stageIndexes?.length ?? 0) > 0
}

/**
 * Задан урок каталога ЦЕЛИКОМ, а не одна его карточка.
 *
 * <p>Такое назначение приходит ссылкой на файл урока, и ученик раньше открывал
 * сам файл в новой вкладке. Но в файле курса нет скрипта заданий — он только
 * переключает режим и переворачивает карточки слов: запись в нём играет, а
 * варианты ответа не нажимаются. Отсюда жалоба «в домашке аудио играет, а
 * задания не нажимаются». Живые задания у урока есть только в кабинете —
 * разобранные на шаги, как у заданной карточки, — туда его и открываем.
 *
 * <p>id урока приходит прямо, если преподаватель выбрал урок в каталоге окна
 * назначения. Из меню материала на занятии его нет — только ссылка на файл, и
 * урок по ней ищется в каталоге, как это делает живой урок.
 *
 * <p>Самодостаточный урок (пробный, диагностика) — не урок каталога: на шаги он
 * не разбирается и ведёт занятие сам, поэтому остаётся файлом.
 */
export function isWholeCatalogLesson(a) {
  if (!a || a.cardId) return false
  // Тест на определение уровня в домашке — как остальные домашние задания (решение
  // владельца 01.10): своей страницей рамкой прямо в «Домашней работе», а не плеером
  // в «Уроках». Там его ответы пишутся по выдаче — преподаватель видит ход ученика, и
  // работа сдаётся; ответы плеера (catalog_lesson_answers) преподавателю не видны
  // вовсе. Движок занятия и рубильник разбора тут ни при чём: тест — не файл урока,
  // его страница одна и та же на любом занятии и без занятия.
  if (isLevelTestUrl(a.fileUrl)) return false
  // Задан КУСОК урока (блок, задание или стадия) — это не «целиком», сколько бы
  // примет урока каталога ни совпало. Такую выдачу ученику нужно открыть самим
  // файлом через render-эндпоинт: там мост, серверная проверка ответов и
  // автоуказка на выданное место, а разобранный на шаги урок всего этого не
  // знает и открылся бы с начала — ровно та жалоба, с которой всё начиналось.
  if (isAddressedPart(a)) return false
  // На main уроки идут по старому формату (разбор на шаги), поэтому «урок каталога
  // целиком» открывается плеером разбора и у занятия с движком FILE: файл курса в
  // рамке — мёртвый (скрипта заданий в нём нет, варианты не нажимаются). Движок
  // занятия здесь намеренно НЕ смотрим; в develop, где живёт формат FILE, это условие
  // остаётся прежним (lessonEngine === 'FILE' → рамка) — при слиянии не терять.
  if (a.catalogLessonId != null) return true
  const url = String(a.fileUrl || '')
  return a.materialType === 'LINK' && CATALOG_LESSON_FILE.test(url) && !isStandaloneLessonUrl(url)
}
