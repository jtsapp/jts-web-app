// Задания с живых уроков (MaterialAssignment) на экране «Домашняя работа».
//
// Это не вторая домашка, а существующий инструмент преподавателя «задать
// материал как ДЗ» из админки. Здесь назначение приводится к форме карточки
// HomeworkList (id/title/status/dueDate/grade), чтобы жить в одном списке с
// обычными работами: у ученика одна «Домашняя работа», а не два раздела про
// одно и то же. Ни сети, ни React — под юнит-тесты.

/** Оценено ли назначение преподавателем (у него нет статусной машины ДЗ). */
export function isMaterialGraded(a) {
  return a?.gradedAt != null || a?.teacherScore != null
}

/**
 * Ответил ли ученик — то есть приложил ли хоть один файл.
 *
 * У назначения нет статусной машины домашки: сдачи, возврата на доработку и
 * «на проверке» у него не бывает. Вложение и ЕСТЬ сдача — другого способа
 * сказать «я сделал» у ученика нет.
 */
export function hasAnswerFiles(a) {
  return (a?.files?.length ?? 0) > 0
}

/**
 * Обязан ли ученик приложить файл, чтобы закрыть это задание.
 *
 * Пока только выданная карточка урока: у неё нет ни проверяемых заданий, ни
 * сессии, поэтому без вложения она со сроком по умолчанию краснела бы
 * просроченной навсегда. Интерактив закрывается своей сессией и оценкой, а
 * обычный файл-материал сейчас так и живёт — расширять сюда его можно, но это
 * отдельное решение, а не побочный эффект.
 */
export function needsAnswerFile(a) {
  return isLessonCard(a)
}

/**
 * Карточка списка из назначения. id с префиксом «m-», чтобы не столкнуться с
 * числовыми id домашних работ; статусов у назначения три — заданное, сданное
 * и проверенное, — а бейджи и просрочку по dueDate дальше считает
 * homeworkStateKey, как у обычной работы.
 */
export function materialCard(a) {
  return {
    id: `m-${a.id}`,
    kind: 'material',
    // Задали одну карточку урока — она и есть название задания. «Unit 3» про
    // одну карточку из тридцати не сообщает ученику ничего: он не поймёт, что
    // именно ему задали, пока не откроет урок и не пролистает его целиком.
    title: a.cardTitle || a.materialTitle,
    // «Сдано» у назначения выражается двумя разными способами, и это не
    // небрежность, а два разных задания. Карточку урока закрывает ВЛОЖЕНИЕ:
    // проверяемых заданий в ней нет. Урок, заданный целиком, закрывает СДАЧА
    // внутри самого урока — файла он не требует, и без submittedAt такая
    // работа со сроком по умолчанию краснела бы просроченной навсегда.
    //
    // «Проверено» у урока целиком держится на сдаче, а не на одной оценке:
    // возврат на доработку снимает submittedAt и auto_*, а gradedAt с баллом
    // оставляет. Оставь мы здесь голое isMaterialGraded — возвращённая работа
    // лежала бы у ученика проверенной, пока экран урока принимал бы по ней
    // новую сдачу. У остальных заданий сдачи нет вовсе, и для них правило
    // прежнее: оценка закрывает.
    status: isMaterialGraded(a) && (!isWholeLesson(a) || isSubmitted(a))
      ? 'COMPLETED'
      : hasAnswerFiles(a) || isSubmitted(a)
        ? 'SUBMITTED'
        : 'ASSIGNED',
    dueDate: a.dueDate ?? null,
    grade: a.teacherScore ?? null,
    // Процент автопроверки виден ученику прямо в списке: он и есть результат
    // сданного урока до того, как преподаватель поставит оценку.
    autoPercent: a.autoPercent ?? null,
    assignment: a,
  }
}

/** Интерактив открывается через render-эндпоинт (с bridge-скриптом), остальное — прямой файл. */
export function isInteractiveMaterial(a) {
  return a?.materialType === 'INTERACTIVE_HTML'
}

/**
 * Назначена одна карточка живого урока, а не материал целиком.
 *
 * <p>Такое задание открывается НЕ файлом в новой вкладке, а самим уроком в
 * кабинете: у карточки бывает аудио с относительным путём и картинки из
 * словарной колоды того же урока — вне урока они не работают. Поэтому и
 * выдаётся адрес, а не снимок.
 */
export function isLessonCard(a) {
  return !!a?.cardId && a?.catalogLessonId != null
}

/**
 * Назначен урок каталога ЦЕЛИКОМ.
 *
 * <p>Только по флагу и никак иначе. Выводить из `cardId == null` нельзя: та же
 * пара «урок есть, карточки нет» уже сегодня означает «материал урока каталога
 * файлом» — старый диалог назначения сам кладёт catalogLessonId и без
 * карточки. Без явного флага новая выдача неотличима от старой ни в базе, ни
 * здесь, и ученик открывал бы файл вместо урока.
 */
export function isWholeLesson(a) {
  return a?.wholeLesson === true
}

/**
 * Работа сдана — у урока целиком это единственный признак.
 *
 * <p>Статусной машины у назначения нет вовсе: «сдано» до сих пор выражалось
 * наличием приложенного файла. Урок сдаётся без файла, и выразить его сдачу
 * больше нечем.
 */
export function isSubmitted(a) {
  return a?.submittedAt != null
}
