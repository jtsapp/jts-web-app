// Разбор урока каталога на шаги («экстрактор») против показа самим файлом.
//
// Решение владельца 18.09.2026 — показывать файл без экстракции — уточнено
// 22.09.2026 (вариант B, spec-lesson-engine-coexistence): занятия, заведённые ДО
// выката, остаются с разбором (у них уже есть домашки-карточки), новые идут
// файлом. Признак хранит само занятие (LessonResponse.engine), решает
// engineOf(), а не эта константа. Тот же признак читает рабочая область
// преподавателя (web-admin, engineOf там же) — стороны обязаны открывать один
// материал одинаково, иначе преподаватель видит файл, а ученик — карточки.
//
// Константа осталась аварийным рубильником: enabled: true возвращает ВСЕ
// занятия к разбору одной строкой, без миграции. Объект, а не const-литерал —
// тестам и аварийному режиму нужно поднять и опустить.
export const LESSON_EXTRACTOR = { enabled: false }

/** Движок занятия; нет поля или нет занятия — STEPS (прод-поведение до выката). */
export function engineOf(lesson) {
  if (LESSON_EXTRACTOR.enabled) return 'STEPS'
  return lesson?.engine ?? 'STEPS'
}
