import { useEffect, useRef } from 'react'

/**
 * Преподаватель сообщает ученику, что читает его экран, — и перестаёт, когда
 * перестал.
 *
 * Отправка живёт отдельным хуком, а не строчкой в обработчике клика, по двум
 * причинам, каждая из которых уже стоила бага.
 *
 * **Смотрят не того, на кого нажали.** Первый участник выставляется в
 * `reviewStudentId` сам при загрузке урока, и его работа сразу видна в центре
 * экрана; в уроке один на один кнопку «Смотреть экран» нажимать не на кого.
 * Поэтому источник правды — «чей экран сейчас читают» (`studentId`), а не
 * «кому нажали кнопку».
 *
 * **Событие живёт одно мгновение.** Брокер ничего не хранит и не переигрывает
 * на подписку: ученик, который подключился позже, нажал F5 или на минуту
 * потерял связь, подписался бы уже после публикации и метки не увидел до конца
 * урока. Поэтому объявление повторяется каждый раз, когда связь появилась
 * заново или когда сам ученик вернулся в класс (`online`).
 *
 * @param {object}   p
 * @param {number|null} p.studentId  чей экран читают прямо сейчас; null — ничей
 * @param {boolean}  p.connected     установлена ли связь: publish до CONNECT молча теряется
 * @param {boolean}  p.online        в классе ли этот ученик (по присутствию)
 * @param {function} p.sendWatch     (studentId, watching) → публикация
 */
export function useWatchAnnounce({ studentId, connected, online, sendWatch }) {
  // Кому реально ушло «смотрю»: нужно, чтобы снять метку при выходе с урока,
  // когда эффект уже не успевает — сокет закрывается раньше него.
  const announcedRef = useRef(null)

  useEffect(() => {
    if (!connected || studentId == null || !online) return undefined
    announcedRef.current = studentId
    sendWatch(studentId, true)
    return () => {
      // Ушли на другую вкладку, переключились на другого, закрыли урок — метку
      // снимаем. Ученик, ушедший из класса, ничего не получит, но и метки у
      // него уже нет: страницу он закрыл.
      sendWatch(studentId, false)
      announcedRef.current = null
    }
  }, [connected, studentId, online, sendWatch])

  return announcedRef
}
