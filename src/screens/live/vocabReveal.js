/**
 * Переворот карточки словаря, показанный классу.
 *
 * Преподаватель нажимает карточку, чтобы показать перевод, — до этого переворот
 * был чисто местным состоянием на обеих сторонах, и ученик ничего не видел.
 *
 * Едет по уже существующему каналу шагов (`step-progress`), тем же, которым
 * приезжает правка ответа: заводить ради переворота отдельный канал и миграцию
 * не за что. Отличается префиксом в `questionId` — ответом это событие не
 * является, и в ответы ученика попадать не должно.
 */
export const VOCAB_REVEAL_PREFIX = 'vocab-card:'

/** Адрес карточки в канале: слово, а не порядковый номер — он у сторон свой. */
export function vocabRevealId(word) {
  return `${VOCAB_REVEAL_PREFIX}${String(word ?? '').trim()}`
}
