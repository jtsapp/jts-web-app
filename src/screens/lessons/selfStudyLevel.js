// Выбранный уровень в разделе «Самостоятельно».
//
// Уровень жил в состоянии экрана, а экран размонтируется на входе в урок:
// ученик открывал урок с A1, возвращался кнопкой «К урокам» — и попадал на
// свой верхний уровень, потому что состояние начиналось заново. Для того, кто
// проходит курс подряд снизу, это значит искать своё место после каждого урока.
//
// Хранится у ученика в браузере, а не на сервере: это удобство выбора, а не
// его работа. Ошибочное значение ничего не ломает — оно всё равно сверяется с
// тем, что ученику открыто (см. SelfStudy), и не найденное откатывается к
// умолчанию.
//
// Значение — id курса каталога. Раньше здесь лежал код уровня CEFR, но курсов
// одного уровня теперь бывает несколько (общий B2 и Business English с тем же
// кодом), и код перестал указывать на курс. Старое значение по-прежнему
// читается: код ведёт на первый курс этого уровня и при первом показе
// переписывается на id (findPickedCourse в selfStudyCourses.js).
const KEY = 'self-study-level'

export function readSelfStudyLevel() {
  try {
    return localStorage.getItem(KEY) || null
  } catch {
    // Приватный режим и запрет на хранилище — не повод ронять раздел.
    return null
  }
}

export function writeSelfStudyLevel(code) {
  try {
    if (code) localStorage.setItem(KEY, code)
  } catch {
    /* см. выше */
  }
}
