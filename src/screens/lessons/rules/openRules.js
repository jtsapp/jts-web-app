/**
 * Открыть правила школы — вкладку «Правила» «Уроков» — С НАЧАЛА (кнопка на «Главной» и «Правила школы» в Профиле,
 * задача 190). Переход между экранами прокрутку окна не сбрасывает (замер 16.11.2026: «Главная» на 500 px → правила
 * открывались на тех же 500 px, посреди «Общих положений»), а обе кнопки лежат ниже первого экрана. Документ читают
 * сверху — поднимаем окно до перехода. Отдельный модуль, а не функция «Главной»: Профиль не должен тянуть её чанк.
 */
export function openRules(onNav) {
  if (typeof window !== 'undefined') window.scrollTo(0, 0)
  onNav?.('lessons', { tab: 'rules' })
}
