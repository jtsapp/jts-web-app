/**
 * Шаги урока, которые ученику видно.
 *
 * Урок каталога прикреплён к разделу ОДНИМ материалом, а ученику открывается
 * разобранным на шаги. Поэтому «Скрыть от ученика» на материале прятало всё
 * занятие целиком, хотя преподаватель в этот момент смотрит на одно упражнение.
 * Теперь скрытые шаги перечислены у материала раздела, и выкидывает их клиент:
 * вырезать на сервере нельзя — шаги приезжают из каталога, где один и тот же
 * урок общий для всех занятий, а скрыты они в конкретном занятии.
 *
 * Сравнение по строке: id шага в файле урока — строка, а в списке скрытых он
 * мог оказаться числом (через JSON и обратно) — иначе шаг «молча» не скрылся бы.
 */
export function visibleSteps(steps, hiddenStepIds) {
  const all = steps || []
  const hiddenList = hiddenStepIds || []
  if (!hiddenList.length) return all
  const hidden = new Set(hiddenList.map(String))
  return all.filter((step) => !hidden.has(String(step?.id)))
}
