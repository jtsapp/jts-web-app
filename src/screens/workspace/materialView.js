/**
 * Что показать в центре: разобранный урок, файл или ожидание.
 *
 * Порядок здесь не косметический. Материал раздела может оказаться уроком
 * каталога — тогда он открывается шагами, — а может остаться файлом; какой
 * именно, известно только после похода в каталог. Пока ответа нет, файл
 * открывать нельзя: бэкенд вшивает в отрендеренный материал бридж, а тот
 * сохраняет свой поток событий по ключу (урок, материал, ученик). По тому же
 * ключу лежат ответы урока из шагов — и мелькнувший на полсекунды iframe
 * успевал записать поверх них пустой список. Ученик открывал урок и находил
 * свою работу стёртой.
 */
export function materialView({ hasStep, fileUrl, catalogResolved }) {
  if (hasStep) return 'steps'
  if (fileUrl && !catalogResolved) return 'loading'
  return 'file'
}
