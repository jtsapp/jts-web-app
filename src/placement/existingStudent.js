// «Уже наш ученик» — аккаунт заведён до выкатки теста уровня v16. Таким тест не навязываем (решение владельца
// 14.10.2026: «не заставлять, а просто пусть на главной будет выходить как не пройденный»): роадмап не размывается,
// на «Главной» — только отметка «Тест уровня не пройден» с кнопкой.
//
// Признак — дата создания аккаунта из /user/me (UserResponse.createdAt бэкенда), а не уровень: новый аккаунт,
// выданный менеджером, тоже приходит с тарифным уровнем, а ему положен полный путь (тур → закрытый роадмап → тест).

// Выкатка на дев-стенд. Бэкенд отдаёт LocalDateTime без зоны — время сервера (Алматы), поэтому и граница в нём.
export const PLACEMENT_V16_SINCE = '2026-10-15T00:00:00+05:00'

/** true — аккаунт старше выкатки. Даты нет (старый бэкенд, сеть) — считаем новым: полный путь безопаснее пропуска. */
export function isExistingStudent(createdAt, since = PLACEMENT_V16_SINCE) {
  if (!createdAt || typeof createdAt !== 'string') return false
  const iso = /[zZ]|[+-]\d\d:?\d\d$/.test(createdAt) ? createdAt : `${createdAt.slice(0, 19)}+05:00`
  const t = Date.parse(iso)
  return Number.isFinite(t) && t < Date.parse(since)
}
