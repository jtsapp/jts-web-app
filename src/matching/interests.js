export function interestLabel(lang, item) {
  return LABELS[lang]?.[item] ?? item
}

export function toggleInterest(list, item) {
  if (list.includes(item)) return { list: list.filter((x) => x !== item), error: null }
  if (list.length >= MAX_INTERESTS) return { list, error: 'limit' }
  return { list: [...list, item], error: null }
}
