export const TEXTS = { ru, kk, en }

export function matchingText(lang, key, vars) {
  let s = (TEXTS[lang] && TEXTS[lang][key]) ?? TEXTS.ru[key] ?? key
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k])
  return s
}

// Русские формы числа: 1 урок / 2 урока / 5 уроков. В казахском и английском формы различают сами ключи словаря.
export function pluralForm(n) {
  const a = Math.abs(n) % 100
  const b = a % 10
  if (a > 10 && a < 20) return 'many'
  if (b === 1) return 'one'
  if (b >= 2 && b <= 4) return 'few'
  return 'many'
}

export function useMatchingT() {
  const { lang } = useI18n()
  const t = useCallback((key, vars) => matchingText(lang, key, vars), [lang])
  return { t, lang }
}

// «General English · гарантия · уроки по 60 мин · 2 раза в неделю» (ТЗ §2.1.1) — только чтение.
export function tariffLineText(lang, tariff) {
  if (!tariff) return ''
  const parts = [matchingText(lang, 'tariff.' + tariff.name)]
  if (tariff.guarantee) parts.push(matchingText(lang, 'tariff.guarantee'))
  parts.push(matchingText(lang, 'tariff.duration', { n: tariff.duration }))
  parts.push(matchingText(lang, 'tariff.perWeek.' + pluralForm(tariff.perWeek), { n: tariff.perWeek }))
  return parts.join(' · ')
}

