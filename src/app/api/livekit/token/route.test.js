import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { POST } from './route.js'

vi.mock('@/lib/auth-server.js', () => ({
  resolveProfileId: async () => ({ id: 'device-test' }),
  bearerFromRequest: () => null,
  fetchTutorLimitOverride: async () => null,
}))
vi.mock('@/lib/usage.js', async (importOriginal) => ({
  ...(await importOriginal()),
  isDbConfigured: () => false,
}))

async function issue(roomName) {
  const response = await POST(new Request('http://localhost/api/livekit/token', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ room: roomName }),
  }))
  expect(response.status).toBe(200)
  const payload = await response.json()
  const claims = JSON.parse(Buffer.from(payload.token.split('.')[1], 'base64url'))
  return { payload, claims }
}

describe('tutor room dispatch', () => {
  beforeEach(() => {
    vi.stubEnv('LIVEKIT_API_KEY', 'test-key')
    vi.stubEnv('LIVEKIT_API_SECRET', 'test-secret-test-secret-test-secret')
    vi.stubEnv('LIVEKIT_URL', 'wss://example.invalid')
    vi.stubEnv('LIVEKIT_AGENT_NAME', '')
  })
  afterEach(() => vi.unstubAllEnvs())

  it('preserves automatic dispatch when no worker name is configured', async () => {
    const { payload, claims } = await issue('existing-tutor-room')
    expect(payload.room).toBe('existing-tutor-room')
    expect(claims.roomConfig).toBeUndefined()
  })

  it('dispatches only into a fresh tutor room generated by the server', async () => {
    vi.stubEnv('LIVEKIT_AGENT_NAME', 'jts-tutor')
    const first = await issue('video-call-room')
    const second = await issue('video-call-room')
    expect(first.payload.room).toMatch(/^jts-tutor-/)
    expect(first.payload.room).not.toBe(second.payload.room)
    expect(first.claims.video.room).toBe(first.payload.room)
    expect(first.claims.roomConfig.agents.map(({ agentName }) => agentName)).toEqual(['jts-tutor'])
  })
})
