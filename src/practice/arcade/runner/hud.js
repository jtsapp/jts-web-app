// Шапка Word Rush: что из состояния забега показать над сценой. Здесь — только то, что надо проверять без сцены и
// React (RunnerGame.jsx рисует three.js, и в тесте его не поднять).

// Плашка «слово = перевод» после промаха. Только на промахе: верные ворота ученик и так знает, а плашка с эталоном —
// единственное место, откуда помощник по сайту узнаёт верный ответ ряда (RunnerGame вешает его в
// data-assistant-expected). Ряд к этому моменту уже проехал, и ответить на него заново нельзя — эталон ничего не
// подсказывает; слово с ошибкой колода вернёт через несколько рядов, но перевод игра показала ученику сама.
export function missToast(s, seconds) {
  const last = s?.last
  if (!last || last.hit || !(s.elapsed - last.at < seconds)) return null
  return { prompt: last.prompt, answer: last.answer }
}
