// Какой уровень «Грамматики · игр» открыт при входе (Д11): по уровню профиля
// ученика. Уровни раздела — диапазоны «откуда → куда» (L1 «0 → A1», L2 «A1 →
// A2» …), и уровень профиля — их начало: ученик с A2 занят темами «A2 → B1».
// Прототип помнил последний открытый уровень в localStorage; на сайте выбор
// живёт до ухода с экрана, а следующий заход снова начинается с профиля.

const TABLE = { A0: 'L1', A1: 'L2', A2: 'L3', B1: 'L4', B2: 'L5', C1: 'L5', C2: 'L5' }

export function levelOf(userLevel) {
  const k = String(userLevel || '').trim().toUpperCase().slice(0, 2)
  return TABLE[k] || 'L1'
}
