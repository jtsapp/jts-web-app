// Автостоп записи фразы (баг ревью #63). Раньше «по очереди» запись обрывалась
// через длину фразы + 3 с, без учёта скорости: ученик, который повторяет
// медленнее спикера или слушал фразу на 0.5×, терял конец своей реплики, а
// оценка потом снимала баллы за «пропущенные» слова.
import { describe, it, expect } from 'vitest'
import { autoStopMs } from './engine.js'

describe('autoStopMs — «по очереди»', () => {
  it('короткой фразе даёт заметно больше, чем «длина + 3 с»', () => {
    // 2 с фразы: было 5 с, теперь 7 с — время на реакцию и медленный темп.
    expect(autoStopMs([0, 2, 'Hi there.'], 1, false)).toBe(7000)
  })

  it('медианная фраза (6 с) повторяется в полтора раза медленнее и не обрывается', () => {
    // 6 × 1.5 = 9 с речи + 4 с запаса.
    expect(autoStopMs([10, 16, 'x'], 1, false)).toBe(13000)
  })

  it('на замедленном видео считает от услышанной длины, а не от длины в ролике', () => {
    // 6 с фразы на 0.5× звучат 12 с — ученик копирует этот темп.
    expect(autoStopMs([10, 16, 'x'], 0.5, false)).toBe(22000)
  })

  it('длинная фраза на 0.5× упирается в потолок, а не растёт бесконечно', () => {
    expect(autoStopMs([0, 20, 'x'], 0.5, false)).toBe(60000)
  })

  it('самой длинной фразе урока (20 с) на 1× хватает времени договорить', () => {
    // Было min(20, 20 + 3) = 20 с — запас ноль, конец фразы резался всегда.
    expect(autoStopMs([0, 20, 'x'], 1, false)).toBeGreaterThanOrEqual(30000)
  })
})

describe('autoStopMs — «синхрон»', () => {
  it('прежний расчёт: услышанная длина + 0.6 с хвоста', () => {
    expect(autoStopMs([0, 4, 'x'], 1, true)).toBe(4600)
    expect(autoStopMs([0, 4, 'x'], 0.5, true)).toBe(8600)
  })
})

describe('autoStopMs — битые данные', () => {
  it('нулевая скорость и перевёрнутые тайминги не дают NaN и отрицательных чисел', () => {
    const ms = autoStopMs([5, 3, 'x'], 0, false)
    expect(Number.isFinite(ms)).toBe(true)
    expect(ms).toBeGreaterThan(0)
  })
})
