// Время перевода выделения (/api/writing/translate) — одно на клиента и роут,
// поэтому отдельным модулем. Роут обязан ответить РАНЬШЕ, чем клиент сдастся:
// иначе перевод списан из дневного лимита и оплачен, а ученик уже смотрит
// пословный подстрочник. Так и было: клиент ждал 12 с (таймаут прототипа), а
// сервер — 10 с на вызов × 3 попытки ретраев SDK плюс паузы между ними, 31 с
// и дольше.
//
// Haiku переводит фрагмент за 0.8–1.9 с (замер 12.10.2026: 12 фрагментов по
// 8–79 символов, без сбоев), так что 10 с роута — с запасом на один повтор
// при перегрузке модели, а 2 с до клиентского потолка — на сеть.
export const TRANSLATE_DEADLINE_MS = 10000
export const TRANSLATE_CLIENT_TIMEOUT_MS = 12000
