// Строки теста, которые приложение показывает иначе, чем бандл школы.
//
// `strings.js` целиком генерируется скриптом из бандла (scripts/extract-placement.js),
// поэтому правки прямо в нём затираются на следующем прогоне. Всё, что должно
// отличаться именно в приложении, живёт здесь и накладывается поверх.

import { T } from './strings.js'

const OVERRIDES = {
  ru: {
    // В бандле хвост «Задания с картинками появятся после пилота»: внутренняя
    // деталь про этап разработки, ученику она ничего не объясняет.
    a0Note: 'Начнём с самого простого: два коротких вопроса.',
  },
  kk: {
    a0Note: 'Ең қарапайымнан бастайық: екі қысқа сұрақ.',
  },
  en: {
    a0Note: "Let's start with the very basics: two short questions.",
  },
}

/** Строка теста с учётом переопределений приложения. */
export function placementText(lang, key) {
  const dict = OVERRIDES[lang] || OVERRIDES.ru
  return key in dict ? dict[key] : T(lang, key)
}
