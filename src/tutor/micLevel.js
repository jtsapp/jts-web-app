// Уровень «тебя слышат» для кнопки микрофона в звонке.
//
// Зачем вообще: пока ученик тянет длинный ответ, тьютор молчит намеренно —
// он ждёт конца мысли, а не завис. Без индикации эта пауза читается как
// оборванная связь, и ученик начинает переспрашивать «алло?». Голосом
// поддакивать не стали: «mhm» поверх речи сбивает с мысли и утекает обратно
// в распознавание, поэтому сигнал только визуальный.

// Ниже этого — дыхание, вентилятор, шум комнаты. Без порога кнопка дышала бы
// в тишине, и сигнал перестал бы что-либо значить.
export const MIC_FLOOR = 0.02

// Громкость с микрофона живёт в районе сотых; множитель растягивает рабочий
// диапазон обычной речи на всю шкалу, потолок держит кольцо в разумных
// размерах на крике.
const GAIN = 3

/**
 * @param {number} volume громкость трека (0..1) от useTrackVolume
 * @param {{ micOn?: boolean, listening?: boolean }} state состояние звонка
 * @returns {number} 0 — не показывать кольцо; 0..1 — насколько оно раздуто
 */
export function micLevel(volume, { micOn = false, listening = false } = {}) {
  // Мьют и «тьютор сейчас говорит» одинаково означают, что показывать нечего:
  // в первом случае его физически не слышат, во втором очередь не его.
  if (!micOn || !listening) return 0
  if (!Number.isFinite(volume) || volume <= MIC_FLOOR) return 0
  return Math.min(1, volume * GAIN)
}
