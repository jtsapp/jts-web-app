// Выбор модуля «Обучения» под уровень.
//
// Модуль нужен не ради содержимого — тропа и сами уроки берутся из статики, —
// а ради его id: по нему считается прогресс и применяется квота «сколько
// уроков модуля можно пройти» (см. ContentQuotaService на бэкенде). Нет id —
// нет и проверки: завершение уходит на модульный эндпоинт, который награждает,
// но ничего не ограничивает.
//
// Уровней с несколькими модулями миграция не создаёт, но запрета на них нет
// (см. комментарий в V211): берём первый по orderIndex — тот же порядок, что у
// остальных клиентов, иначе на разных устройствах считался бы разный модуль.

export function pickLevelModule(modules, level) {
  const want = String(level || '').toUpperCase()
  if (!want || !Array.isArray(modules)) return null
  return (
    modules
      .filter((m) => String(m?.level || '').toUpperCase() === want)
      .sort((a, b) => (a?.orderIndex ?? 0) - (b?.orderIndex ?? 0))[0] || null
  )
}

/**
 * Номер модуля на момент завершения урока — с одной переспрашивающей попыткой.
 *
 * `moduleId === null` возникает по двум разным причинам, и на экране они
 * выглядят одинаково: модуля для уровня правда нет — или список модулей не
 * загрузился при входе. Разница дорогая: во втором случае завершение урока
 * уходит на модульный эндпоинт, который начисляет награду, но ничего не
 * ограничивает, и прогресс не попадает на бэкенд вовсе. То есть одна сетевая
 * осечка при входе снимала главный демо-лимит («3 узла тропы») на весь визит и
 * не оставляла следа, по которому это можно было бы наверстать позже.
 *
 * Поэтому переспрашиваем ровно там, где ответ нужен для решения, а не гоняем
 * повторы фоном: к моменту завершения урока сеть обычно уже вернулась.
 *
 * Возвращает новое состояние целиком, чтобы вызывающий не гадал, сбрасывать ли
 * флаг: «спросили и получили пустой список» — это уже не «не смогли спросить»,
 * и повторять запрос на каждом следующем уроке незачем.
 */
export async function resolveModuleId({ moduleId, modulesUnavailable, level, fetchModules }) {
  if (moduleId != null || !modulesUnavailable) {
    return { moduleId, modulesUnavailable }
  }
  try {
    const mod = pickLevelModule(await fetchModules(), level)
    return { moduleId: mod ? mod.id : null, modulesUnavailable: false }
  } catch {
    // Всё ещё недоступен: остаёмся в прежнем состоянии, чтобы следующий урок
    // попробовал снова.
    return { moduleId: null, modulesUnavailable: true }
  }
}
