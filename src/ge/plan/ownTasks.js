// Свои задачи плана General English — урок курса и практика, которые план собрал сам. Занятия, домашка и всё, что
// поставил преподаватель (origin = teacher, в том числе его практика), в «Сегодня» не входят: ТЗ v2.0 9.1 и решение
// владельца 07.11.2026 — они живут в «Уроках с преподавателем» (на «Главной» пока — расписание и домашка в правой
// колонке) и в полном плане. Одно правило на блок «Сегодня» и на профиль Луны: модуль без импортов, чтобы его брал и
// серверный contextLines, не таща за planModel каталог шэдоуинга.

/** Задача плана — своя (урок курса или практика плана), а не занятие, домашка или задача преподавателя. */
export function isOwnTask(task) {
  return (task?.kind === 'course' || task?.kind === 'practice') && task?.origin !== 'teacher'
}

/**
 * Бэкенд умеет «У меня мало времени» (ТЗ v2.0, 5.2): новый план всегда отдаёт поле shortDay (null — не выбрано). Без
 * поля бэкенд прежний и ручки пересчёта нет — кнопку не показываем и Луне метку не даём, иначе ученик получал бы «не
 * удалось» на каждое нажатие. Здесь, а не в replan.js: его тянет серверный contextLines, а replan.js импортирует api.js.
 */
export function canReplan(plan) {
  return Boolean(plan && plan.state === 'ready' && Object.prototype.hasOwnProperty.call(plan, 'shortDay'))
}
