export const TEXTS = { ru, kk, en }

export function groupText(lang, key, vars) {
  let s = (TEXTS[lang] && TEXTS[lang][key]) ?? TEXTS.ru[key] ?? key
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k])
  return s
}

export function useGroupT() {
  const { lang } = useI18n()
  const t = useCallback((key, vars) => groupText(lang, key, vars), [lang])
  return { t, lang }
}
