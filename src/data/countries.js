// Страны для селектора кода в телефонном вводе регистрации/входа.
// dial — код страны без «+»; [min, max] — длина НАЦИОНАЛЬНОГО номера (без кода)
// для валидации и маски. Флаги — эмодзи (компактно, без набора SVG); на
// мобильных таргетах (iOS/Android/macOS) отрисовываются корректно.
//
// ВНИМАНИЕ: канонический вид номера для бэкенда — цифры кода+номера без «+»
// (см. normalizePhone в api.js). Для Казахстана/России это «7XXXXXXXXXX» —
// тот же формат, в котором уже зарегистрированы существующие пользователи,
// поэтому вход по OTP для них не ломается.
//
// Список был закрытым и коротким, и это оказалось не мелочью: страны нет в
// списке — номер ввести НЕЧЕМ, регистрация и вход упираются в тупик. Отсюда
// просьба «принимают не только +7, а то есть студенты и учителя не из Кз».
// Поэтому здесь два уровня:
//
//   1. Страны с выверенной длиной номера (первые — СНГ и соседи, дальше те,
//      откуда к онлайн-школе приходят чаще всего). Для них маска и проверка
//      точные.
//   2. {@link OTHER_COUNTRY} — «Другая страна»: человек набирает номер целиком
//      с кодом, проверяем по E.164 (7–15 цифр). Выдумывать точные длины для
//      каждой страны мира не станем: неверная длина хуже отсутствующей —
//      она молча не пускает того, у кого номер как раз правильный.

/** Предел E.164: код страны и номер вместе — не больше 15 цифр. */
export const E164_MAX = 15;

/** Длина национального номера, когда точной нормы для страны у нас нет. */
function loose(dial) {
  return { min: 6, max: E164_MAX - dial.length };
}

function c(iso, name, dial, flag, len) {
  return { iso, name, dial, flag, ...(len ?? loose(dial)) };
}

