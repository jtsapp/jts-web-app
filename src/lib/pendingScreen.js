/**
 * Экран, на который человек шёл по ссылке, но сначала вынужден был войти.
 *
 * Диплинк `?screen=…` применяется и гостю — раздел открывается сразу. Но стоит
 * пойти логиниться, и намерение пропадало: адрес чистит эффект синхронизации
 * (экраны входа в `?screen=` не пишутся — см. PERSISTABLE_SCREENS в App.jsx), а
 * после входа экран назначает homeScreenFor. Человек, открывший присланную
 * ссылку на текст «Чтения», после входа оказывался на «Главной» и искал этот
 * текст руками.
 *
 * ПОЧЕМУ sessionStorage, А НЕ ПЕРЕМЕННАЯ В ПАМЯТИ. Вход — это не один клик:
 * между «пришёл по ссылке» и «вошёл» лежит ввод кода из SMS, а туда ходят в
 * другое приложение и возвращаются, иногда обновив вкладку. Переменная в
 * памяти такого не переживает, а namespace вкладки — да, и умирает вместе с
 * ней: чужой ссылке в соседней вкладке или завтрашнему визиту она не достанется.
 *
 * ПОЧЕМУ ЧИТАЕТСЯ ОДИН РАЗ. Намерение живёт до первого применения: не съев его,
 * мы бы возвращали человека на присланный текст при КАЖДОМ следующем входе в
 * этой вкладке — в том числе после выхода из аккаунта и входа под другим.
 */

const KEY = 'jts_pending_screen'

/** Запомнить, куда человек шёл. Пусто/не строка — стираем: нечего помнить. */
export function rememberPendingScreen(screen) {
  try {
    if (typeof screen === 'string' && screen) window.sessionStorage.setItem(KEY, screen)
    else window.sessionStorage.removeItem(KEY)
  } catch {
    /* приватный режим или квота — намерение просто не переживёт вход */
  }
}

/**
 * Забрать намерение и сразу его забыть.
 *
 * @returns имя экрана либо null. Вызывающий обязан проверить, что такой экран
 *          вообще открывается по адресу: значение могло лечь ещё прошлой
 *          версией приложения, где экран назывался иначе.
 */
export function consumePendingScreen() {
  try {
    const screen = window.sessionStorage.getItem(KEY)
    window.sessionStorage.removeItem(KEY)
    return screen || null
  } catch {
    return null
  }
}

/** Экран урока: имя вынесено, потому что правило ниже опирается на него поимённо. */
const LESSON_WORKSPACE = 'lesson-workspace'

/**
 * Куда вести после входа: годится ли запомненное намерение.
 *
 * `persists` — умеет ли этот экран открываться по адресу (PERSISTABLE_SCREENS в
 * App.jsx). Проверять обязательно: значение могло лечь ещё прошлой версией
 * приложения, где экран назывался иначе, и человек получил бы пустоту вместо
 * кабинета.
 *
 * УРОК С КАРТОЧКОЙ — ИСКЛЮЧЕНИЕ, И НАМЕРЕННОЕ. В PERSISTABLE_SCREENS экран
 * урока не входит: без своего id он открылся бы демонстрационным уроком, то
 * есть чужим материалом. Но ссылка на карточку, заданную на дом, — это ровно та
 * присланная ссылка, ради которой человек и логинится: он открыл домашку с
 * телефона, вкладка попросила войти, и после входа он обязан оказаться на
 * заданной карточке, а не на «Главной», где это задание ещё надо найти.
 * Поэтому для него спрашиваем не имя экрана, а то, что адрес карточки
 * действительно прочитан из ссылки.
 *
 * @returns имя экрана либо null — «веди на домашний экран роли».
 */
export function pendingScreenAfterLogin(pending, { persists, hasCardAddress = false } = {}) {
  if (!pending) return null
  if (pending === LESSON_WORKSPACE) return hasCardAddress ? pending : null
  return persists?.(pending) ? pending : null
}

/** Выход из аккаунта: чужое намерение следующему в этой вкладке не достаётся. */
export function clearPendingScreen() {
  try {
    window.sessionStorage.removeItem(KEY)
  } catch {
    /* нечего чистить */
  }
}
