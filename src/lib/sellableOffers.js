// Что можно купить онлайн прямо сейчас. Сервер помечает предложение purchasable: false, когда оно опубликовано, но
// заказ на него не создастся (нет тарифа, срока, уровней Self Study) — «Купить» у такого вело к 422 и в чат менеджера.
// Нет поля вовсе (старый бэкенд) — считаем продаваемым, как было до онлайн-продаж.
export function sellableOffers(list) {
  return (Array.isArray(list) ? list : []).filter((o) => o && o.purchasable !== false)
}
