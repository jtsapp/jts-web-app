// Указание модели ученика рядом с вопросом (спека модели ученика, раздел 6). Профиль — данные, и строку «Совет
// методики» Haiku 5.5 там пропускала: на «Что дальше?» при десяти верных быстрых подряд советовала только домашку
// (зонд 08.11.2026, M04 0 из 3), а повторение по расписанию ставила вместо шагов плана (M02 0 из 3). Правила об этом в
// RULES она пропускает так же, как другие (замеры 15–28.10), поэтому — рядом с вопросом, как указания turnHints.js, и
// только когда в профиле есть сами строки: без них указание было бы про пустое.
//
// Модуль свой, а не строка в turnHints.js: там шаблоны учителя, и их меняют отдельно.

const METHOD = 'Совет методики'
const REVIEW = 'Повторение по расписанию'

/**
 * @param {{ studentContext?: string|null, screenText?: string }} p
 * @returns {string[]} строки указания (пусто — указывать нечего)
 */
export function modelHints({ studentContext, screenText = '' } = {}) {
  const ctx = String(studentContext || '')
  const out = []
  if (ctx.includes(METHOD)) {
    // Правило «3 ошибки подряд — объясни правило» Haiku выполняла парой «go → went» — это и есть ответ (зонд 08.11.2026,
    // M03 2 из 3). С того же дня раунд игры помечен заданием (data-assistant-task), и общее «не называй ответ» от
    // openingFocus встаёт и здесь; эта строка остаётся — она про пару «глагол → форма», которой общее указание не ловит.
    if (/_{3,}/.test(String(screenText || ''))) {
      out.push('На экране задание с пропуском «___»: его ответ не называй нигде — ни в правиле, ни в примере, ни парой «глагол → форма» для глагола из задания; пример — на другом глаголе.')
    }
    out.push(
      `В профиле «Темп сейчас» и «${METHOD}» — методика сайта: держим около 80 % верных; 3 ошибки подряд или ниже 80 % — объяснение и шаг проще; всё верно и быстро — шаг сложнее. Если ученик спрашивает, что делать дальше, как у него дела или просит помочь с заданием, — одной-двумя фразами скажи то, что советует методика, адрес бери из её метки; своих заданий не придумывай. Слова «методика» и «темп» ученику не называй — своими словами, как преподаватель («всё верно и быстро — можно сложнее»). Ответ задания на экране не называй и не подсказывай вариантом: пример — на другом слове.`,
    )
  }
  if (ctx.includes(REVIEW)) {
    out.push(`«${REVIEW}» из профиля — дополнение к плану: на вопрос, что делать сегодня, сначала шаги «Плана на сегодня» (и горящая домашка), повторение — после них, а не вместо.`)
  }
  return out
}
