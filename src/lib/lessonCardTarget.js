import { findCardById } from './lessonCardId.js'
import { groupBlocks } from '../screens/workspace/LessonContent.jsx'

/**
 * Куда вести ученика по адресу карточки: шаг урока и якорь на экране.
 *
 * Отдельно от самого адреса, потому что это две разные вещи. Адрес карточки —
 * то, что задал преподаватель, и он хранится в выдаче. Якорь — то, куда
 * подъезжает экран, и он живёт по правилам показа.
 *
 * ЗАЧЕМ ПЕРЕВОД, А НЕ ПРЯМОЙ ИНДЕКС. Лента урока показывает не сырые блоки:
 * идущие подряд info-блоки склеиваются в одну карточку (groupBlocks), и якорь у
 * такой карточки — индекс ПЕРВОГО блока серии. Возьми мы сырой индекс, для
 * второго info-блока серии якоря просто не существовало бы: экран открылся бы
 * на нужном шаге, но не подъехал никуда, и ученик остался бы искать задание
 * глазами. Ровно на этом расхождении сырого и схлопнутого индексов уже стоят
 * два несовместимых ключа в уроке — скрытие считает по сырому, «проверено» по
 * схлопнутому.
 */
export function cardTarget(lesson, cardId) {
  const found = findCardById(lesson, cardId)
  if (!found) return null

  const step = (lesson?.steps ?? []).find((s) => String(s.id) === found.stepId)
  const groups = groupBlocks(step?.blocks ?? [])
  // Группа, в которую попал блок: у склеенной серии он может быть не первым.
  const group = groups.find((g) =>
    g.block === found.block || (g.blocks ?? []).includes(found.block))

  return {
    stepId: found.stepId,
    // Якоря может не быть, если блок вырезан из показа (скрыт преподавателем) —
    // тогда ведём хотя бы на шаг, это честнее пустого экрана.
    anchorId: group ? `block-${group.blockIndex}` : null,
  }
}
