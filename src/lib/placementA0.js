// Варианты для A0-моста пробного урока — на сервере.
//
// Мост показывает те же два задания движка, что и тест, но вместо ввода даёт
// выбрать слово. Раньше варианты собирал клиент прямо из `item.answer`, и это
// работало ровно до тех пор, пока ответы лежали в публичном банке. Их оттуда
// убрали (bankSplit.js), и клиенту стало неоткуда взять верный вариант: на
// экране появлялись четыре кнопки, из которых одна пустая, и ни одной верной.
//
// Что здесь отдаётся наружу и почему это приемлемо. Ответ не называется — в
// ответе четыре слова в перемешанном порядке, как и на экране. Это осознанный
// размен: мост — обучающий шаг пробного урока, а оценка идёт через
// /api/placement/grade, где ключей по-прежнему нет.
//
// Две вещи, без которых подсказка утекала бы всё равно:
//
// 1. Отвлекающие ВЫБИРАЮТСЯ СЛУЧАЙНО из набора, а не берутся его началом. Иначе
//    и к `works`, и к `can` подставлялись бы первые три — `is, are, am`, и
//    верным оказывалось бы просто единственное слово другого рода. Мост
//    проходился бы стратегией «выбрать непохожее», без знания языка.
//
// 2. Сид включает номер прогона, а не только id задания. Иначе порядок кнопок
//    был бы один и тот же у всех и навсегда, и позиция верного ответа стала бы
//    общеизвестной константой. Мост это ворота: два верных ответа сбрасывают θ
//    на A1 (`bridgeVerdict`) и возвращают ученика в основной тест.

import { seededShuffle } from '../practice/placement/engine.generated.js'
import { rngFor } from '../practice/placement/bankSplit.js'
import { loadFullBank } from './placementScore.js'

/** Отвлекающие: служебные слова уровня A0, из которых собран сам мост. */
export const A0_DISTRACTORS = Object.freeze([
  'is', 'are', 'am', 'do', 'does', 'can', 'have', 'work', 'works', 'went',
])

const norm = (s) => String(s || '').trim().toLowerCase()

/** Сколько вариантов на задании: верный плюс три отвлекающих. */
export const A0_OPTION_COUNT = 4

/**
 * Варианты для перечисленных заданий моста: { id: [четыре слова] }.
 *
 * [runSeed] — номер прогона (`session.seed` у клиента). Он делает набор и
 * порядок своими у каждого прохождения, оставаясь стабильным внутри одного:
 * повторный запрос той же пары (id, прогон) вернёт то же самое, и кнопки под
 * рукой у ученика не перетасуются.
 *
 * Задания без ключа или не из моста молча пропускаются — экран пробного урока
 * ветвится по наличию `a0options` и без них покажет обычное поле ввода.
 */
export function buildA0Options(ids, runSeed = null, source = loadFullBank()) {
  const keys = source.keys || {}
  const byId = new Map((source.bank?.items || []).map((it) => [it.id, it]))
  const suffix = Number.isFinite(runSeed) ? `:${runSeed >>> 0}` : ''
  const out = {}

  for (const id of ids || []) {
    const item = byId.get(id)
    if (!item || item.block !== 'a0_bridge') continue

    const answers = keys[id]?.answer || []
    const correct = answers[0]
    if (!correct) continue

    // Один ГПСЧ на задание: им и тасуем набор отвлекающих, и раскладываем
    // готовые кнопки. Два обращения к одному потоку, а не два независимых сида.
    const rnd = rngFor(`${id}${suffix}`)
    const wrong = seededShuffle(A0_DISTRACTORS.slice(), rnd)
      .filter((w) => !answers.some((a) => norm(a) === norm(w)))
      .slice(0, A0_OPTION_COUNT - 1)

    out[id] = seededShuffle([correct, ...wrong], rnd)
  }
  return out
}
