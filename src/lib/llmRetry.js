// Повтор платного вызова модели — СВОИМ циклом, а не ретраями SDK.
//
// У SDK по умолчанию два повтора, и каждый со своим таймаутом: вызов с
// timeoutMs 45 000 на деле может идти 45 × 3 с лишним. Прод стоит за
// Cloudflare, который рвёт запрос после 100 с молчания (524), а клиент
// сдаётся ещё раньше — разбор, оплаченный учеником, уходил в пустоту.
// Поэтому роуты зовут structured() с maxRetries: 0 и повторяют сами, только
// если до своего потолка осталось на повтор время.
//
// Отдельный модуль, а не anthropic.js: тесты роутов подменяют anthropic.js
// целиком, а решать «повторять ли» должна настоящая проверка.

import Anthropic from '@anthropic-ai/sdk'

// Сбой, который повтор того же запроса может вылечить: сеть и таймаут,
// 408/409/429 и 5xx (529 — перегрузка). 400/401/403/404 и отказ модели
// повтор не лечит — там ответ будет тем же.
export function isRetryableLlmError(e) {
  if (e instanceof Anthropic.APIConnectionError) return true
  const status = Number(e?.status)
  return status === 408 || status === 409 || status === 429 || status >= 500
}
