// Тип занятия и состав класса — два вопроса, на которые и живой урок, и
// расписание отвечали каждый по-своему, считая участников. Ответы разъезжались:
// в группе, где остался один записавшийся, урок подписывался «Индивидуальный»,
// а отменившийся ученик стоял в составе класса как ни в чём не бывало.

/** Типы занятий, которые ведут не с одним учеником (LessonType на бэкенде). */
const GROUP_TYPES = new Set(['GROUP', 'PAIR'])

/** Статусы участника, означающие, что на уроке его не будет (ParticipantStatus). */
const GONE_STATUSES = new Set(['CANCELLED_FREE', 'CANCELLED_BURNED', 'NO_SHOW_BURNED'])

/**
 * Групповое занятие или один на один — по типу самого урока.
 *
 * Возвращает null, когда тип неизвестен (урок ещё не загрузился или пришёл без
 * поля): «не знаю» и «индивидуальный» — разные ответы, и звать их одним словом
 * значит рисовать чип «Индивидуальный» на всём, что не успело приехать.
 *
 * Парное занятие считается групповым: один на один оно не является.
 */
export function isGroupLesson(lesson) {
  const type = lesson?.lessonType
  if (!type) return null
  return GROUP_TYPES.has(type)
}

/**
 * Участники, которые на уроке будут: бэкенд отдаёт список вместе с
 * отменившимися и не пришедшими, а состав класса — это те, с кем занимаются.
 */
export function activeParticipants(participants) {
  return (participants || []).filter((p) => !GONE_STATUSES.has(String(p?.status || '')))
}
