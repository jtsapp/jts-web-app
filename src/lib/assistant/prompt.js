/**
 * Начало ответа модели: метка «не по теме», обычный ответ или пока не ясно
 * (текст пуст или ещё может оказаться меткой — «[[OFF…»).
 * @returns {'offtopic'|'normal'|'undecided'}
 */
export function classifyStart(text) {
  const head = String(text ?? '').trimStart()
  if (head.startsWith(OFFTOPIC_MARKER)) return 'offtopic'
  if (OFFTOPIC_MARKER.startsWith(head)) return 'undecided'
  return 'normal'
}

const MAX_CLIENT_ERRORS = 8

function parseClientErrors(raw) {
  if (!Array.isArray(raw)) return []
  return raw.slice(0, MAX_CLIENT_ERRORS).map((e) => ({
    at: Number(e?.at) || 0,
    message: clipText(e?.message, 400),
    source: clipText(e?.source, 200),
    url: clipText(e?.url, 400),
    stack: clipText(e?.stack, 1200),
  })).filter((e) => e.message)
}

/**
 * Системный промпт: правила + разделы для перехода + база знаний. Одинаков для
 * всех с одной персоной (Луна или Айзере — по языку интерфейса, persona.js), поэтому кэшируется.
 */
export function buildSystemPrompt(persona = PERSONAS.luna) {
  return `${rulesFor(persona)}\n\n## Разделы, которые ты умеешь открывать\n\n${destinationsText()}\n\n## База знаний о сайте\n\n${knowledgeText(persona)}`
}

const clipText = (s, n) => {
  const str = String(s ?? '').trim()
  return str.length > n ? `${str.slice(0, n)}…` : str
}

/**
 * Проверка тела запроса от виджета. Бросает AssistantRequestError на мусоре,
 * длинное подрезает: помощник должен ответить, а не упасть на лишнем абзаце.
 *
 * @returns {{ messages: {role: 'user'|'assistant', content: string}[],
 *             screen: {id: string|null, text: string}, lang: string,
 *             pageUrl: string, userAgent: string,
 *             errors: {at: number, message: string, source: string, url: string, stack: string}[],
 *             bugReported: boolean, voice: boolean }}
 */
const CALL_ROOM_RE = /^jts-luna-[a-z0-9]{1,16}-\d{10,16}$/

export function parseChatRequest(body) {
  if (!body || typeof body !== 'object') throw new AssistantRequestError('Пустой запрос')
  const raw = Array.isArray(body.messages) ? body.messages : null
  if (!raw || raw.length === 0) throw new AssistantRequestError('Нет сообщений')

  const messages = raw
    .filter((m) => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string')
    .map((m) => ({ role: m.role, content: clipText(m.content, MAX_MESSAGE_CHARS) }))
    .filter((m) => m.content)
    .slice(-MAX_TURNS)

  // Модели нужен разговор, который начинается с ученика и им же кончается.
  while (messages.length && messages[0].role !== 'user') messages.shift()
  if (!messages.length || messages[messages.length - 1].role !== 'user') {
    throw new AssistantRequestError('Последним должно быть сообщение ученика')
  }

  const screenId = typeof body.screen?.id === 'string' ? body.screen.id.slice(0, 64) : null
  const screenText = typeof body.screen?.text === 'string' ? clipText(body.screen.text, MAX_SCREEN_CHARS) : ''
  const lang = LANG_NAMES[body.lang] ? body.lang : 'ru'
  const pageUrl = typeof body.pageUrl === 'string' ? clipText(body.pageUrl, 500) : ''
  const userAgent = typeof body.userAgent === 'string' ? clipText(body.userAgent, 400) : ''
  const errors = parseClientErrors(body.errors)
  const bugReported = Boolean(body.bugReported)
  const voice = Boolean(body.voice)
  // Вопрос из звонка Луне — имя его комнаты (api/assistant/call). Роут сверит
  // её с базой и даст квоту звонка; здесь только форма, чтобы мусор не ушёл в SQL.
  const call = typeof body.call === 'string' && CALL_ROOM_RE.test(body.call) ? body.call : null

  return { messages, screen: { id: screenId, text: screenText }, lang, pageUrl, userAgent, errors, bugReported, voice, call }
}

/**
 * Контекст текущего вопроса: кто спрашивает и что у него на экране. Едет в
 * последнем сообщении ученика — то есть модель видит только СВЕЖИЙ экран, а
 * снимки прошлых ходов в историю не копятся (и не раздувают каждый запрос).
 */
export function buildContextBlock({ user, screen, lang, studentContext, errors, pageUrl, today }) {
  const lines = []
  const name = clipText(user?.name, 60)
  if (name) lines.push(`Имя ученика: ${name}`)
  if (user?.languageLevel) lines.push(`Уровень в профиле: ${clipText(user.languageLevel, 8)}`)
  lines.push(`Язык интерфейса: ${LANG_NAMES[lang] || LANG_NAMES.ru}`)
  // Сроки домашки и занятия идут датами (studentContext.js) — без сегодняшней
  // модель гадала «уже просрочено» / «уже завтра» про срок через два дня.
  if (today) lines.push(`Сегодня: ${today}`)
  const screenName = screen?.id ? SCREEN_NAMES[screen.id] || screen.id : null
  const destId = screen?.id ? destinationIdForScreen(screen.id) : null
  if (screenName) lines.push(`Открытый раздел: ${screenName}${destId ? ` (id для метки: ${destId})` : ''}`)
  if (pageUrl) lines.push(`Адрес страницы: ${clipText(pageUrl, 500)}`)
  lines.push('Снимок экрана (что ученик видит сейчас):')
  lines.push(screen?.text ? screen.text : '(пусто — экран не удалось прочитать)')
  if (errors?.length) {
    lines.push('Технические сбои, которые сайт уже заметил (это не слова ученика):')
    for (const e of errors) {
      const when = e.at ? new Date(e.at).toISOString() : ''
      const where = [e.source, e.url].filter(Boolean).join(' · ')
      lines.push(`- ${when} ${e.message}${where ? ` @ ${where}` : ''}`)
      if (e.stack) lines.push(e.stack.split('\n').slice(0, 4).join('\n'))
    }
  }
  // Профиль ученика — только если удалось собрать (studentContext.js, сам
  // модуль отказоустойчив и кэширует). Нужен для плана «на неделю»; для
  // разбора задания хватает снимка экрана, поэтому его отсутствие не критично.
  if (studentContext) {
    lines.push('Профиль ученика (для плана и советов; чего здесь нет, того не знаешь):')
    lines.push(studentContext)
  }
  return `<контекст>\n${lines.join('\n')}\n</контекст>`
}

/** Разговор для модели: к последнему вопросу ученика приклеен контекст. */
export function buildTurns({ messages, user, screen, lang, studentContext, errors, pageUrl, voice, today }) {
  const turns = messages.map((m) => ({ role: m.role, content: m.content }))
  const last = turns[turns.length - 1]
  const opening = isOpeningTurn(last.content)
  const focus = opening ? openingFocus(screen?.text) : { task: false, unchecked: false }
  // Открытие окна — не «вопрос ученика»: подпись «Вопрос ученика: [ученик открыл
  // окно]» читалась бы как его слова.
  // Язык — рядом с пометкой, а не только «Язык интерфейса» в <контекст>: вопроса,
  // по которому его видно, нет, и при казахском интерфейсе Haiku отвечала
  // по-русски — на языке правил (замер 15.10.2026).
  // Что на экране задание и не проверено ли оно, решает код (openingFocus): правила
  // об этом в RULES Haiku 5.5 пропускала, а указание рядом с пометкой — нет. По той же
  // причине на экране задания модели не дают «Совет сайта» и пометку «вспомни»:
  // посреди урока она звала с них в домашку.
  // Позывной (opening.js): ученик сам позвал — Луна здоровается и спрашивает, чем помочь.
  // Указание — рядом с пометкой по той же причине, что у открытия окна. Совета раздела
  // нет: ученик сейчас скажет, что ему нужно, — поэтому и «Совет сайта» из профиля убран.
  const wake = isWakeTurn(last.content)
  const answerLang = `Язык ответа: ${LANG_NAMES[lang] || LANG_NAMES.ru}`
  // Обычный вопрос на непроверенном задании — то же указание рядом с вопросом: на
  // «проверь» Haiku 5.5 сама оценивала выбор ученика и называла верный вариант («задание
  // ждало «don't like»» — зонд 21.10.2026, 3 из 3), хотя RULES это запрещают; подсказкой
  // ей служил значок 👎 в задании. С указанием она жмёт «Проверить» и молчит об ответе.
  const unchecked = !opening && !wake && openingFocus(screen?.text).unchecked
  const ask = wake
    ? [
        WAKE_MARK,
        answerLang,
        `Ученик сам позвал тебя голосом («${assistantPersona(lang).wakeExample}»). Поздоровайся коротко — по имени, если оно есть, и на «вы»; одной фразой скажи, что видишь на экране; спроси, чем помочь. Раздел не советуй и метку не ставь.`,
        ...(focus.unchecked ? ['Задание ещё не проверено: не оценивай введённый ответ и не называй правильный.'] : []),
        'Не больше 3 коротких предложений.',
      ].join('\n')
    : opening
      ? [
          OPENING_MARK,
          answerLang,
          ...(focus.task ? ['На экране задание: говори только о нём — без советов про другие разделы, без прошлых советов и без метки. Ошибку из разговоров со Speaking Buddy на то же правило назвать можно.'] : []),
          ...(focus.unchecked ? ['Задание ещё не проверено: не оценивай введённый ответ и не называй правильный — только подсказка.'] : []),
          'Не больше 4 коротких предложений.',
        ].join('\n')
      : unchecked
        ? `Вопрос ученика: ${last.content}\n\nЗадание на экране ещё не проверено: не оценивай выбор или ввод ученика и не называй правильный ответ — только подсказка или нажатие кнопки, о которой он просит.`
        : `Вопрос ученика: ${last.content}`
  const context = focus.task || wake ? withoutAdvice(studentContext) : studentContext
  last.content = `${buildContextBlock({ user, screen, lang, studentContext: context, errors, pageUrl, today })}\n\n${ask}${voice ? `\n\n${VOICE_MARK}` : ''}`
  return turns
}

/** Профиль без «Совета сайта» и без пометки «вспомни» — для первой реплики на экране задания. */
function withoutAdvice(studentContext) {
  if (!studentContext) return studentContext
  return String(studentContext)
    .split('\n')
    .filter((line) => !line.startsWith('Совет сайта'))
    .map((line) => line.replace(`  ${RECALL_MARK}`, ''))
    .join('\n')
}
