// Указания рядом с вопросом ученика — то, что правила (RULES в prompt.js) просят, а Haiku
// 5.5 держит только рядом с вопросом. Так уже работают «не оценивай непроверенное»,
// «язык ответа» и каталог «Что можно открыть»: правило в системном промпте модель
// пропускала, указание у вопроса — нет (замеры 15–28.10.2026).
//
// Зонд ТЗ v2.0 (07.11.2026, 18 сценариев × 20 ответов, правила этапа 0 только в RULES):
// к ученику по-прежнему «ты был», «ты сказала» (13 из 20 на «не пришёл»), объяснение
// правила без типичной ошибки и проверочного вопроса (0/20), перевод без альтернатив
// (0/20), проверка текста без «что получилось» и исправленного текста целиком (2/20),
// ученику Self Study расписывались правила переноса уроков, которых у него нет (8/20).
//
// Чистый модуль: что за вопрос, решает код по словам, а не модель. Ложное срабатывание
// стоит одной лишней строки указания — модель ему всё равно следует по смыслу.

const RULE_ASK = /(объясн|разниц|чем отлича|когда (используют|используется|ставится|нужен|нужно)|правил[оау]|как образ|түсіндір|айырмашы|ереже|explain|difference between|when do (we|i) use)/i
const TRANSLATE_ASK = /(перев[её]д|перевести|переведи|как (будет|сказать|написать) .*по-английски|как по-английски|аудар|translate)/i
const CHECK_ASK = /(провер|исправ|ошибк|тексер|check|correct)/i
const COMPLAINT_ASK = /(жалоб|пожаловат|недовол|груб|хамит|опазд|не отвечает|не выходит на связь|отзыв|похвалить|шағым|complain|complaint|feedback)/i
const TOKENS_ASK = /(токен|приз|token|prize)/i
const TODAY_ASK = /(что (мне )?(делать|сделать|заниматься)|чем заняться|с чего начать|план на (сегодня|день|неделю)|бүгін не|не істеу|what should i do|what to do today)/i
// «Почему на Главной 32%, а в Профиле 73%?» — проценты навыков на двух экранах.
const SKILL_NUMBERS_ASK = /(\d+\s*%|процент|пайыз).*(главн|профил|басты)|(главн|профил|басты).*(\d+\s*%|процент|пайыз)/i
const LESSON_ASK = /(перенест|перенос|отмен|урок|занят|сабақ|lesson|reschedule)/i
// «Мало времени» (ТЗ v2.0, 5.2 и событие short_on_time): «у меня 15 минут», «спешу», «уақытым аз».
const LOW_TIME_ASK = /(мало времени|нет времени|времени (мало|нет)|спешу|тороплюсь|(есть|осталось|у меня) (всего |только )?(минут \d+|\d+\s*(мин|минут))|только \d+\s*мин|уақыт(ым)? (аз|жоқ)|асығып|\d+\s*минут(ым|ым бар)|short on time|no time|in a hurry|(only|just) \d+\s*min)/i
// \S, а не \w: в JS \w видит только латиницу, и «обычный план» не ловился бы
const LOW_TIME_RESET = /(обычн\S* план|верни (мне )?план|вернуть план|әдеттегі жоспар|usual plan|normal plan)/i
// Ответ на её «Сколько есть: 10, 20 или 30 минут?» — одно число («20», «минут 15», «20 минут»).
const MINUTES_ONLY = /^\s*(минут\s*)?\d{1,3}\s*(мин\S*|min\S*)?\s*[.!]?\s*$/i
// План по дням есть, если в профиле строка «План на сегодня (…)» (contextLines.gePlanToday), и пересчёт возможен —
// нет строки REPLAN_OFF (прежний бэкенд без ручки). Текст строки — тот же, что в contextLines.
const hasPlan = (studentContext) => {
  const s = String(studentContext || '')
  return s.includes('План на сегодня (') && !s.includes('Пересчитать день под «мало времени» сейчас нельзя.')
}

// Английский текст для проверки: хотя бы три латинских слова подряд по смыслу.
const latinWords = (s) => (String(s).match(/[A-Za-z]{2,}/g) || []).length

/** Формат ученика из строки профиля (format.js) — для указания у вопроса. */
export function formatOfContext(studentContext) {
  const line = String(studentContext || '').split('\n').find((l) => l.startsWith('Формат обучения:')) || ''
  if (/Self Study/.test(line)) return 'self_study'
  if (/демо-доступ/.test(line)) return 'demo'
  if (/с преподавателем/.test(line)) return 'with_teacher'
  return null
}

/**
 * Обращение — для любого хода, где модель пишет ученику: «ты»; по-казахски — «сен». Род — только по полу из Профиля
 * (решение владельца 07.11.2026): указан — в этом роде, не указан — без рода. По имени пол не угадываем.
 * @param {'ru'|'kk'|'en'} answerLang язык ответа
 * @param {'MALE'|'FEMALE'|null} [gender] пол ученика из Профиля
 */
export function addressHint(answerLang, gender = null) {
  if (answerLang === 'en') return ''
  // Названия разделов — по-казахски: база знаний русская, и без этого в казахский ответ
  // попадали «Чтение», «Мой словарь» (зонд 07.11.2026, 4 из 20).
  if (answerLang === 'kk') return 'Обращение — на «сен» (сен, саған, сенің; «жаз», «таңда», «көр»), без «сіз» и окончаний -ңыз/-ңіз. Разделы называй по-казахски, как в казахском интерфейсе (Сөздік, Оқылым, Тыңдалым, Айтылым, Үй жұмысы), без русских слов.'
  // Пол указан в Профиле — обычный русский с родом: «без рода» читается натужно («твой ответ отмечен» вместо «ты ответила»).
  // «Вам» во множественном («вам с преподавателем») — тоже «вы» для ученика: зонд 07.11.2026, 2 из 20.
  const plural = ' «Вы», «вам», «ваш» нельзя и во множественном значении: не «вам с преподавателем», а «тебе и преподавателю».'
  if (gender === 'FEMALE') return 'Обращение — на «ты». В Профиле указан женский пол: к ученице — в женском роде («ты выбрала», «готова?», «сама»).' + plural
  if (gender === 'MALE') return 'Обращение — на «ты». В Профиле указан мужской пол: к ученику — в мужском роде («ты выбрал», «готов?», «сам»).' + plural
  // Род: модель брала его из имени («Айгерим» — «ты выбрала»; зонд 07.11.2026, в 7–14 из 20).
  // «Примеры через «мы»» пробовали — модель стала менять «I» на «we» в исправленном тексте ученика (зонд, 4 из 20).
  return 'Обращение — на «ты» и без рода: пол ученика не указан, даже если имя кажется женским или мужским. Не «ты был», «ты сделала», «как бы ты сказал», а «у тебя», «твой ответ», «как скажешь».' + plural
}

/**
 * Указания под вопросом ученика: шаблоны учителя, жалоба, токены, план на сегодня, формат.
 * @param {{ question: string, studentContext?: string|null, unchecked?: boolean }} args
 *   unchecked — на экране непроверенное задание: «проверь» там — нажать «Проверить», а не разбор текста
 * @returns {string[]}
 */
export function questionHints({ question, studentContext = null, unchecked = false, previous = '', answerLang = 'ru' }) {
  const q = String(question || '')
  const hints = []
  const askedMinutes = MINUTES_ONLY.test(q) && /(мин|minut)/i.test(previous) && /\?/.test(previous)
  // «мало времени» — без указания «Дай план на сегодня» ниже: «верни обычный план на сегодня» ловил и его, и модель
  // пересказывала весь день, теряя метку (зонд 07.11.2026: 0 из 20, метки нет в 7). «От 5 до 180» модель пересказывала
  // ученику («нужно выбрать 15, а не 5»). Язык — явно и с образцом: русское указание у казахского вопроса тянуло ответ
  // на русский (10 из 20, а с «на языке вопроса» — 17 из 20), строки «Язык ответа» там нет — язык вопроса = интерфейса.
  let lowTime = false
  const kk = answerLang === 'kk'
  if (LOW_TIME_RESET.test(q) && hasPlan(studentContext)) {
    lowTime = true
    hints.push(
      `Ученик просит вернуть обычный план на сегодня: одной короткой фразой скажи, что возвращаешь, и последней строкой [[REPLAN_NOW 0]]. Сам план не пересказывай и шагов не советуй: какой он, сайт покажет сразу после ответа.${kk ? ' Ответ — по-казахски, например: «Жарайды, бүгінгі әдеттегі жоспарды қайтарамын.»' : ''}`,
    )
  } else if (LOW_TIME_ASK.test(q) || askedMinutes) {
    lowTime = true
    hints.push(
      hasPlan(studentContext)
        ? `Ученику мало времени. Назвал минуты — одной короткой фразой скажи, что пересобираешь план на сегодня под них, и последней строкой [[REPLAN_NOW N]], где N — названные им минуты числом. Какие задачи останутся, покажет сайт сразу после твоего ответа: не перечисляй их и не называй своих. Минут не назвал — одним вопросом спроси, сколько есть: 10, 20 или 30 минут, без метки.${kk ? ' Ответ — по-казахски, например: «Жарайды, бүгінгі жоспарды 10 минутқа қайта құрамын.» или «Бүгін қанша уақытың бар: 10, 20 әлде 30 минут?»' : ''}`
        : `Ученику мало времени, а плана по дням у него нет: предложи один короткий шаг на это время — раздел «Совета сайта», с его меткой последней строкой. Метку [[REPLAN …]] не ставь.${kk ? ' Ответ — по-казахски.' : ''}`,
    )
  }
  const textToCheck = CHECK_ASK.test(q) && latinWords(q) >= 3
  if (textToCheck && !unchecked) {
    hints.push('Это проверка текста: сначала одной фразой, что конкретно получилось (что верно); потом настоящие ошибки — не больше 3, стилистику не считай — строками «было → стало → почему»; в конце — исправленный текст целиком.')
  } else if (TRANSLATE_ASK.test(q)) {
    hints.push('Это просьба о переводе: основной вариант и 1–2 альтернативы; для каждой — чем отличается по смыслу и когда уместна, а не только «разговорно / официально»; ключевая конструкция — одной фразой.')
  } else if (RULE_ASK.test(q) && !unchecked) {
    hints.push('Это вопрос о правиле: ответь по шаблону — когда используется (простыми словами), форма схемой, 2–3 коротких английских примера, частая ошибка русско- и казахскоязычных учеников, а в конце — один проверочный вопрос ученику.')
  }
  if (COMPLAINT_ASK.test(q)) {
    hints.push('Это жалоба или отзыв: коротко посочувствуй (или поблагодари) и обязательно назови путь словами: раздел Feedback → «Жалоба на преподавателя», «Жалоба на менеджера», «Жалоба на платформу» или «Хороший отзыв о преподавателе» — какая подходит. Ученик сказал, что случилось, — вопрос «Открыть с черновиком?» и последней строкой [[FEEDBACK категория | черновик]]: категория — одно слово teacher, manager, platform или review, черновик — 1–3 предложения от первого лица только из его слов. Подробностей нет — путь с категорией всё равно назови словами, затем одним вопросом спроси, что случилось, и последней строкой [[OPEN feedback]]; ничего не обещай отправить или передать сама. Почту и сроки ответа не называй.')
  }
  if (SKILL_NUMBERS_ASK.test(q)) {
    hints.push('Это про проценты навыков на двух экранах. По базе знаний Главная и Профиль считают одинаково — по заданиям текущего уровня. Не придумывай разницу формул, выборок или уровней и не называй своих причин и догадок («не успели обновиться», «задержка», «сбой»): причины ты не знаешь. Скажи, что считают одинаково, предложи обновить страницу; цифры всё равно разные — предложи передать команде.')
  }
  if (TOKENS_ASK.test(q)) {
    hints.push('Про токены и призы — только по статье «Токены и призы» базы знаний. Её нет — значит, у ученика их на сайте нет: так и скажи. Есть — назови все главные правила: за что начисляются, обмен на призы, ночное списание в будний день без активности и что одной практики за день достаточно, чтобы токены не списались.')
  }
  if (TODAY_ASK.test(q) && !lowTime) {
    hints.push('Дай план на сегодня: 2–3 шага по порядку, у каждого — причина и примерное время; первый шаг — с меткой его раздела последней строкой. Не говори «всё сделано», если в профиле есть просроченная или открытая домашка.')
  }
  const format = formatOfContext(studentContext)
  if ((format === 'self_study' || format === 'demo') && LESSON_ASK.test(q)) {
    hints.push(
      format === 'demo'
        ? 'У ученика демо-доступ: уроков с преподавателем у него нет — так и скажи, правил переноса не расписывай; можно предложить бесплатный пробный урок.'
        : 'Ученик на Self Study: уроков с преподавателем и домашки от него у него нет — так и скажи, правил переноса не расписывай.',
    )
  }
  return hints
}
