// Позывной Луны: «Привет, Луна» / «Сәлем, Луна» (решение 16.10.2026) и просто
// «Луна» (решение владельца 19.10.2026).
//
// Распознаватель ограничен грамматикой: он выбирает только между этими фразами и
// «чем-то другим» ([unk]), поэтому не «слышит» Луну в каждой реплике урока. Слова
// обязаны быть в словаре модели vosk-model-small-ru-0.22 — проверено по её Gr.fst
// 16.10.2026: «привет», «салем», «луна» есть, «сәлем» и «hey» — нет. Поэтому
// казахское «Сәлем» ловится русским «салем», а английского «Hey, Luna» нет вовсе.
//
// Фразу из двух слов принимаем где угодно в распознанном, а одно имя — только
// когда ученик сказал его ОТДЕЛЬНО (вся реплика — «Луна»). Грамматика тянет любое
// похожее слово к ближайшему варианту: «Посмотри на луну» пришло бы как
// «[unk] луна», а «Она сказала…» — как «луна [unk]», и окно открывалось бы
// посреди чужого разговора. Позвать Луну по имени — сказать «Луна» и замолчать;
// что нужно, она спросит сама.
export const WAKE_PHRASES = ['привет луна', 'салем луна']
export const WAKE_NAME = 'луна'
export const WAKE_GRAMMAR = [...WAKE_PHRASES, WAKE_NAME, '[unk]']

const norm = (s) =>
  String(s ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/ә/g, 'а')
    .replace(/[^a-zа-я\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

/** Финальный текст распознавателя — позывной? Фраза — слова подряд, имя — одно. */
export function matchWake(text) {
  const t = norm(text)
  if (!t) return false
  if (WAKE_PHRASES.some((p) => ` ${t} `.includes(` ${p} `))) return true
  // «луна луна» — то же имя: ученик повторил, не дождавшись окна.
  return t.split(' ').every((w) => w === WAKE_NAME)
}
