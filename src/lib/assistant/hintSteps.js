// Ступени подсказки в задании (ТЗ v2.0, 7.2б и промт 4г; решение владельца 4). Какая ступень сейчас, решает код,
// а не модель: Haiku на «подскажи» то давала наводку, то сразу правило с ответом, и «до проверки ответ не называть»
// держала через раз (замеры 15–28.10.2026). Поэтому окно считает ступени по заданию, а модель получает пометку
// «ступень 2; практика» и указание к ней — что можно и чего нельзя на этой ступени.
//
//   1 — наводка: на что посмотреть;
//   2 — правило и похожий пример на других словах;
//   3 — разбор почти до ответа, без последнего шага (только практика);
//   «ответ» — верный ответ с разбором: только практика и только после 3-й ступени и ещё одной попытки.
//
// Домашка — не больше двух ступеней, ответа никогда; штрафа нет, но ступень уходит преподавателю вместе с ответом
// (HomeworkExercises → saveHomeworkAnswer). Тест, экзамен, mock — подсказок нет вовсе.
//
// Ключ задания модель получает только на 3-й ступени и на «ответе» в практике: его отдаёт сам раздел по запросу окна
// (hintTask.js), в снимке экрана ключа нет. В домашке, тесте и экзамене ключ не берётся никогда — ни окном, ни роутом.
//
// Модуль чистый и общий: пометку разбирает сервер, учёт ступеней ведёт окно (память вкладки + sessionStorage, чтобы
// перезагрузка посреди домашки не обнулила ступень, которую увидит преподаватель).

export const HINT_MODES = ['practice', 'homework', 'test']
// Сколько ступеней у режима; «ответ» — сверх них, только у практики.
export const MAX_STEP = { practice: 3, homework: 2, test: 0 }
export const ANSWER = 'answer'

const MODE_WORD = { practice: 'практика', homework: 'домашка' }
const WORD_MODE = { практика: 'practice', домашка: 'homework' }
const REASON_WORD = { errors: 'ошибка', idle: 'долго без действий', asked: 'сам попросил' }
const WORD_REASON = Object.fromEntries(Object.entries(REASON_WORD).map(([k, v]) => [v, k]))

const MARK_RE = /^\[подсказка: ступень (1|2|3|ответ); (практика|домашка); (ошибка|долго без действий|сам попросил)\]$/

/** Служебный ход «ученик просит подсказку» для модели. */
export function hintMark({ step, mode, reason = 'asked' }) {
  const s = step === ANSWER ? 'ответ' : String(step)
  return `[подсказка: ступень ${s}; ${MODE_WORD[mode] || MODE_WORD.practice}; ${REASON_WORD[reason] || REASON_WORD.asked}]`
}

/** Разобрать служебный ход: { step: 1|2|3|'answer', mode, reason } или null. */
export function parseHintMark(content) {
  const m = MARK_RE.exec(String(content ?? '').trim())
  if (!m) return null
  return { step: m[1] === 'ответ' ? ANSWER : Number(m[1]), mode: WORD_MODE[m[2]], reason: WORD_REASON[m[3]] }
}

export const isHintTurn = (content) => parseHintMark(content) != null

/**
 * Ступень, которую можно дать в режиме, или null — подсказок больше нет (или нет вовсе).
 * @param {{ step?: number|'answer'|0, wrongAfter3?: boolean }} state что уже было на этом задании
 */
export function nextHintStep(mode, state = {}) {
  const max = MAX_STEP[mode] ?? 0
  if (!max) return null
  const cur = state.step === ANSWER ? ANSWER : Number(state.step) || 0
  if (cur === ANSWER) return ANSWER
  if (cur < max) return cur + 1
  // Практика после 3-й ступени: ответ — только когда ученик попробовал ещё раз; иначе повторяем разбор.
  if (mode === 'practice') return state.wrongAfter3 ? ANSWER : 3
  return null
}

// «Подскажи», «ещё подсказку», «көмектес» набранным текстом или голосом — та же ступень, что у кнопки: иначе текстом
// ступени обходились бы, и на «подскажи» модель сама выбирала глубину. Только короткая просьба без другого смысла:
// «подскажи, где словарь» — обычный вопрос (лишние слова остаются — не просьба подсказки).
const HINT_WORD = /(подска|намекн|hint|көмектес|кеңес)/
const HINT_FILLER = /^(луна|айзере|подска\S*|намекн\S*|hints?|көмектес\S*|кеңес\S*|бер\S*|дай|дайте|давай|ещё|еще|можно|пожалуйста|плиз|please|мне|маған|с|со|этим|это|этом|в|по|задани[еяюи]|заданием|тут|здесь|тағы|осы|тапсырма\S*|бір|өтінем|give|me|a|an|another|one|more|can|i|get|some|with|this)$/
export function isHintAsk(text) {
  const t = String(text ?? '').toLowerCase().replace(/[.,!?…:;«»"]/g, ' ').replace(/\s+/g, ' ').trim()
  if (!t || t.length > 60 || !HINT_WORD.test(t)) return false
  return t.split(' ').every((w) => HINT_FILLER.test(w))
}

/** Ключ задания модели можно отдать только на этой ступени и в этом режиме. */
export const keyAllowed = (mode, step) => mode === 'practice' && (step === 3 || step === ANSWER)

/** Ступень для преподавателя (число 1–3): «ответ» — это 3-я плюс показанный ответ. */
export const stepNumber = (step) => (step === ANSWER ? 3 : Number(step) || 0)

// ── Указание модели (сервер, buildTurns) ──────────────────────────────────────────────────────────
// Рядом с пометкой, а не в RULES — по той же причине, что у «застрял» и событий: правила у вопроса Haiku держит.
const STEP_WHAT = {
  1: 'Ступень 1 — наводка: одним-двумя предложениями скажи, на что посмотреть в задании (слово-подсказка, время, кто действует, форма слова рядом). Правило целиком не объясняй и примеров не давай.',
  // Списки форм («see → saw, eat → ate») — зонд 08.11: по-казахски ответ попадал в такой список. Конкретный глагол
  // в самом указании («go → …») подталкивал к нему же — 11 из 20, поэтому указание общее.
  2: 'Ступень 2 — правило и похожий пример: правило в одном-двух предложениях простыми словами и РОВНО один короткий английский пример на ДРУГИХ словах — не из этого задания, без его слов и вариантов, но того же типа (неправильный глагол — другой неправильный глагол). Списков форм не приводи.',
  3: 'Ступень 3 — разбор почти до ответа: по шагам, каждый шаг — короткой фразой (что в задании подсказывает ответ → какое правило здесь работает → как по нему получается нужная форма), и остановись перед последним шагом — саму форму ученик называет сам. Предложи попробовать ещё раз.',
  [ANSWER]: 'Ученик попробовал ещё раз после разбора — теперь назови верный ответ (ключ ниже) и одной-двумя фразами объясни, почему он такой.',
}
const STEP_SENTENCES = { 1: 2, 2: 4, 3: 4, [ANSWER]: 3 }
const REASON_LINE = {
  errors: 'Ответ ученика сайт отметил неверным.',
  idle: 'Ученик давно ничего не делает на этом задании.',
  asked: 'Ученик сам попросил подсказку.',
}

/**
 * Указание к пометке подсказки. key — ключ задания (только practice на 3-й ступени и «ответе», иначе null).
 * @param {{ step: number|'answer', mode: string, reason: string }} hint
 */
export function hintInstruction(hint, { key = null, lang = 'ru' } = {}) {
  // «Ступень 3, сделаем по шагам» и «найди в таблице неправильных глаголов в Практике» — зонд 08.11, 2 из 2.
  const lines = [`Подсказка к заданию на экране. ${REASON_LINE[hint.reason] || REASON_LINE.asked} Без приветствия, без советов про другие разделы и материалы, без прошлых советов и без метки [[…]]. Слово «ступень» и её номер ученику не называй.`]
  lines.push(STEP_WHAT[hint.step] || STEP_WHAT[1])
  if (hint.step !== ANSWER) {
    lines.push('Верный ответ не называй — ни целиком, ни частью, ни как вариант на выбор, ни внутри примера или списка форм. Варианты ответа с экрана не повторяй вовсе — даже во фразе «не скажу, верно ли …». Не оценивай то, что ученик ввёл или выбрал.')
    // По-казахски Haiku называла форму глагола задания в правиле («went — go етістігінің өткен шақ түрі»): 5 из 20 на 2-й
    // ступени при русском запрете (зонд 08.11). Тот же запрет — ещё и на языке ответа.
    if (lang === 'kk') lines.push('Қазақша жауапта да: экрандағы жауап нұсқаларын және тапсырмадағы сөздің дұрыс формасын атама — ережеде де, мысалда да.')
  }
  if (hint.mode === 'homework') {
    lines.push(`Это домашка: подсказок на задание не больше двух${hint.step === 2 ? ', и это последняя' : ''}; ответ не называй никогда, даже если ученик просит прямо. Оценку подсказка не снижает, но преподаватель увидит, что она была.`)
  }
  if (key && keyAllowed(hint.mode, hint.step)) {
    lines.push(
      hint.step === ANSWER
        ? `Ключ задания (сайт отдал его для ответа): «${key}».`
        : `Ключ задания — только для тебя, чтобы разбор был верным: «${key}». Ученику его не называй и не пиши его части; если разбор без последнего шага выдаёт ответ целиком — остановись раньше.`,
    )
  } else if (hint.step === 3 || hint.step === ANSWER) {
    lines.push('Ключа задания у тебя нет: опирайся только на экран; если по экрану верного ответа не видно — не угадывай его, разбери, как его найти.')
  }
  // Длина — по ступени: на второй модель дописывала второй пример и пятое предложение (зонд 08.11, 9 из 40).
  lines.push(`Не больше ${STEP_SENTENCES[hint.step] || 4} коротких предложений.`)
  return lines.join('\n')
}

// ── Учёт по заданию (окно) ────────────────────────────────────────────────────────────────────────
const STORE_KEY = 'jts_luna_hints'
let ledger = null

function load() {
  if (ledger) return ledger
  try {
    ledger = JSON.parse(globalThis.sessionStorage?.getItem(STORE_KEY) || '{}') || {}
  } catch {
    ledger = {}
  }
  return ledger
}

function save() {
  try {
    globalThis.sessionStorage?.setItem(STORE_KEY, JSON.stringify(ledger || {}))
  } catch {
    /* приватный режим — живёт в памяти вкладки */
  }
}

/** Что было на задании: { step, wrongAfter3 } (пусто — подсказок не было). */
export function hintState(taskId) {
  return (taskId && load()[taskId]) || {}
}

/** Окно дало ступень. */
export function recordHint(taskId, step) {
  if (!taskId) return
  const l = load()
  l[taskId] = { step, wrongAfter3: false }
  save()
}

/**
 * Новый неверный ответ на задании. Вернёт true, если подсказки здесь уже были и следующую ступень можно дать сама
 * («второй неверный ответ сам даёт следующую ступень»).
 */
export function noteWrong(taskId) {
  const l = load()
  const s = taskId && l[taskId]
  if (!s?.step) return false
  if (s.step === 3) {
    s.wrongAfter3 = true
    save()
  }
  return true
}

/** Ступень, которую увидит преподаватель (0 — не было). */
export function hintStepFor(taskId) {
  return stepNumber(hintState(taskId).step)
}

/** Для тестов. */
export function resetHints() {
  ledger = {}
  save()
}
