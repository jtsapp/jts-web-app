/**
 * База знаний для промпта. Имя помощника в ней — метками {A} / {A_DAT} (дательный:
 * «помощнику Луне»): при казахском интерфейсе помощник — Айзере (persona.js), и с
 * «Внизу справа — Луна» в базе она называла себя Луной (зонд Haiku 5.5, 19.10.2026).
 * Луна-тьютор Speaking Buddy — другой персонаж, её строки меток не носят.
 *
 * rewards — включены ли на стенде токены и призы (areRewardsEnabled): от него зависит,
 * какая из статей «Монеты» / «Токены» попадёт в базу.
 */
export function knowledgeText(persona = PERSONAS.luna, { rewards = false } = {}) {
  return articlesFor({ rewards })
    .map((a) => `### ${a.title}\n${a.body.join('\n')}`)
    .join('\n\n')
    .replaceAll('{A_DAT}', persona.nameDat)
    .replaceAll('{A}', persona.name)
}

/** Статьи базы для стенда: с токенами или без (поле when). */
export function articlesFor({ rewards = false } = {}) {
  return KNOWLEDGE.filter((a) => !a.when || (a.when === 'rewards') === Boolean(rewards))
}
