// тренажёра. Помощник отвечает на вопросы «как сделать» только из этих статей
// и снимка экрана — чего здесь нет, того он не знает и отправляет к менеджеру
// (см. prompt.js).
//
// Источник — тексты интерфейса (i18n.jsx, i18n/dict.js) и код экранов; числа
// (сколько текстов, глаголов, минут) взяты оттуда же.
//
// Правила для тех, кто правит:
//  - одна статья — один раздел или одна тема; заголовок — как пункт в меню;
//  - только то, что правда на сайте сейчас. Выпустили фичу или убрали кнопку —
//    поправьте статью в том же PR: помощник уверенно повторит устаревшее;
//  - названия кнопок и разделов — дословно как в интерфейсе (i18n.jsx);
//  - цены, скидки и сроки оплаты сюда не пишем: они приходят с бэкенда и
//    меняются, а помощник должен отправлять с этим к менеджеру;
//  - только то, что видит ученик: экраны преподавателя сюда не нужны.
//
// Вся база уходит в системный промпт целиком и кэшируется (anthropic.js), так
