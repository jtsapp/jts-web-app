// Память Луны (ТЗ v2.0, 8.1; решение владельца 08.11.2026): короткие факты, которые ученик сам рассказал и которые
// полезны учёбе, — «готовится к поступлению осенью», «боится говорения», «учится по вечерам». Живут 30 дней (миграция
// 0022, lib/db/assistantFacts.js), едут в профиль Луны и видны ученику в Профиле, каждый можно удалить.
//
// Луна просит запомнить меткой последней строкой: [[REMEMBER боится говорить на уроках]]. Модель решает, ЧТО стоит
// запомнить, но что запомнить НЕЛЬЗЯ — решает код (sensitiveFact): здоровье, деньги, контакты и другие люди не пишутся,
// даже если модель их предложила. Метка вырезается из ответа роутом (actions.js), ученик её не видит.
//
// Модуль чистый: разбирает роут, строку профиля собирает studentContext.

export const FACT_MAX = 120
export const FACT_TTL_DAYS = 30
export const FACTS_CAP = 20 // на ученика: старые вытесняются

/** Факт одной строкой: без скобок, кавычек-ёлочек и переводов строки; не длиннее FACT_MAX. */
export function cleanFact(text) {
  return String(text ?? '')
    .replace(/[[\]«»"]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/[.;,]+$/, '')
    .slice(0, FACT_MAX)
}

// Что не храним (ТЗ 8.1 и решение владельца): здоровье, деньги, контакты, другие люди. Корни ru/kk/en; лучше не
// запомнить лишний раз, чем записать диагноз. Цифры длиннее четырёх подряд — телефон, карта или ИИН.
const SENSITIVE = [
  // здоровье
  /болез|болею|болен|больна|диагноз|депресс|тревожн\S* расстр|лекарств|таблетк|врач|больниц|операци|беремен|инвалид|аллерг|психиатр|психолог|терапи|ауыр|дәрі|ауруха|дәрігер|depress|diagnos|illness|medicat|pregnan|disabilit|therap/i,
  // деньги
  /деньг|денег|зарплат|кредит|ипотек|тенге|₸|\$|€|руб|оплат|заплат|ақша|несие|жалақ|money|salary|debt|loan|\bpaid?\b|price/i,
  // контакты
  /@|https?:|www\.|телефон|адрес|улиц|квартир|whatsapp|telegram|instagram|телеграм|инстаграм|мекенжай|phone|address|e-?mail/i,
  /\d{5,}|\d{3}[\s-]\d{2}[\s-]\d{2}/,
  // «долг», но не «долго» («долго учит слова») — граница по букве
  /(?:^|[^\p{L}])долг(?:а|и|у|ом|ов|ам)?(?![\p{L}])/iu,
  // другие люди. Границы слова — через \p{L}: \b в JS видит только латиницу. Формы — целиком, иначе «сынақ» (тест по-
  // казахски) читался бы как «сын», а «другой» — как «друг». Семья и родители — тоже люди: «семья против» модель
  // предложила запомнить в 1 из 20 (зонд 08.11).
  /(?:^|[^\p{L}])(?:мам[аыуеой]?|пап[аыуеой]?|мать|матер\p{L}*|отец|отц\p{L}*|муж(?:а|у|ем|е)?|жен[аыуеой]|сын(?:а|у|ом|е|ов|овья)?|доч[ьеиюк]\p{L}*|брат(?:а|у|ом|е|ья|ьев)?|сестр\p{L}*|бабушк\p{L}*|дедушк\p{L}*|парень|парн[яюе]\p{L}*|девушк\p{L}*|друз\p{L}*|друг(?:а|у|ом|е)?|подруг\p{L}*|коллег\p{L}*|начальник\p{L}*|семь[яиеюё]\p{L}*|родител\p{L}*|родственник\p{L}*|отбасы\p{L}*|ата-ана\p{L}*|туыс\p{L}*|family|parents?|ребён\p{L}*|ребен\p{L}*|дет(?:и|ей|ям|ьми)|анам|әкем|күйеуім|әйелім|ұлым|қызым|ағам|әпкем|досым|mom|mum|dad|husband|wife|son|daughter|brother|sister|boyfriend|girlfriend|friend|boss|colleague)(?![\p{L}])/iu,
  // …и другие люди без имени: «дома не все поддерживают учёбу» (зонд 08.11, 2 из 40 после фильтра по родне).
  /(?:^|[^\p{L}])(?:близки[ехм]|домашни[ехм]|не\s+(?:все\s+)?поддерживают|против\s+(?:учёбы|учебы|занятий|английского))(?![\p{L}])/iu,
  // политика, религия, интим — не учёба и не наше дело
  /религи|мечет|церк|намаз|политик|партия|секс|интим|religio|politic|sexual/i,
]

/** Чувствительный ли факт — тогда не храним. */
export const sensitiveFact = (fact) => SENSITIVE.some((re) => re.test(String(fact ?? '')))

/** Годный факт для записи или null. */
export function factToSave(raw) {
  const fact = cleanFact(raw)
  if (fact.length < 4 || sensitiveFact(fact)) return null
  return fact
}

// Метка модели. Текст — до закрывающих скобок, без квадратных скобок внутри (иначе метка закрылась бы раньше).
export const REMEMBER_HEAD = '[[REMEMBER'
export const REMEMBER_MARK = /^\[\[REMEMBER\s*:?\s*([^[\]]{3,240})\]\]$/i

/** Сравнение без регистра и знаков — «боится говорения» и «Боится говорения.» один факт. */
export const factKey = (fact) => cleanFact(fact).toLowerCase().replace(/[^\p{L}\p{N} ]/gu, '').trim()

/** Строка профиля для модели; фактов нет — null. */
export function factsLine(facts) {
  const list = (facts || []).map((f) => cleanFact(f?.fact ?? f)).filter(Boolean).slice(0, FACTS_CAP)
  if (!list.length) return null
  return `Память Луны (ученик сам рассказал, хранится 30 дней; опирайся, когда к месту, не пересказывай списком): ${list.map((f) => `«${f}»`).join('; ')}.`
}
