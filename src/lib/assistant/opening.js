// Первая реплика Луны: ученик открыл окно и ничего не спросил — она заговаривает
// сама, как преподаватель, подошедший посмотреть (решение владельца 15.10.2026:
// «он должен быть реальным преподавателем», «когда открываешь — подсказать, что
// правильно, что нет, и что лучше сделать сейчас»).
//
// Пометка — служебный ход ученика: виджет шлёт её вместо вопроса и не рисует, а
// модель видит её в истории. Иначе «да» на её первое «Открыть?» пришло бы без её
// реплики: разговор обязан начинаться с ученика, и сервер срезал бы её. Как
// отвечать на пометку — в правилах (prompt.js), а не в ней самой: правила одни
// для всех и кэшируются.
//
// Отдельным модулем, а не в prompt.js: виджету нужна только пометка, а prompt.js
// тянет за собой базу знаний — в браузерный бандл ей незачем.

export const OPENING_MARK = '[ученик открыл окно]'

// Ученик позвал Луну голосом («Луна», «Привет, Луна», lib/assistant/wake/). Тоже служебный
// ход, но ответ другой: позвали — значит нужна, и Луна здоровается и спрашивает, чем
// помочь, а не советует раздел (решение 16.10.2026).
export const WAKE_MARK = '[ученик позвал голосом]'

/** Служебный ход «ученик позвал голосом». */
export const isWakeTurn = (content) => String(content ?? '').trim() === WAKE_MARK

/**
 * Служебный ход — «ученик открыл окно» или «позвал голосом», а не вопрос, набранный
 * учеником. На оба действуют одни защиты: ни паузы «не по теме», ни отчёта о поломке.
 */
export const isOpeningTurn = (content) => {
  const text = String(content ?? '').trim()
  return text === OPENING_MARK || text === WAKE_MARK
}

// Что на экране, решает код, а не модель. Правила «посреди задания — только о
// задании» и «до проверки — не оценивать» Haiku 5.5 в RULES пропускала: в 2–3
// репликах из 3 звала в домашку посреди урока и говорила про непроверенный ответ
// «не подошёл» (замер 15.10.2026). Поэтому роут ставит прямое указание рядом с
// пометкой и сам снимает кнопку (prompt.js, chat/route.js).
//
// Признаки — из разметки снимка (screenSnapshot.js): поле ответа, кнопка проверки,
// пометки сайта о проверке. Одна «Продолжить» задания не делает: она есть и на
// «Главной» (продолжить курс).
// Без \b: в JS он видит только латиницу, и «[поле:» им не ловилось.
const TASK_SIGNS = /\[(поле|пустое поле)[\s:\]]|\[кнопка «(Проверить|Check|Тексеру)»/i
const CHECKED_SIGNS = /отмечено как (не)?верное|верный вариант, не выбран|Неверный ответ|верный ответ по заданию|Правильный ответ|Верно!/i

/** { task: на экране задание, unchecked: и оно ещё не проверено } */
export function openingFocus(snapshotText) {
  const text = String(snapshotText ?? '')
  const checked = CHECKED_SIGNS.test(text)
  const task = checked || TASK_SIGNS.test(text)
  return { task, unchecked: task && !checked }
}

// Состояние экрана для «один раз на экран»: Луна не повторяет первую реплику,
// если ученик закрыл и снова открыл окно, ничего не поменяв. Цифры выброшены:
// таймер записи, счёт и время плеера тикают сами, и без этого каждое открытие
// считалось бы новым экраном — и платным вызовом модели.
export function screenStateKey(screenId, snapshotText) {
  const text = String(snapshotText ?? '').replace(/\d+/g, '#').replace(/\s+/g, ' ').trim()
  let h = 5381
  for (let i = 0; i < text.length; i++) h = ((h << 5) + h + text.charCodeAt(i)) | 0
  return `${screenId || ''}|${text.length}|${(h >>> 0).toString(36)}`
}
