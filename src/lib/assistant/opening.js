// Первая реплика Луны: ученик открыл окно и ничего не спросил — она заговаривает
// сама, как преподаватель, подошедший посмотреть (решение владельца 15.10.2026:
// «он должен быть реальным преподавателем», «когда открываешь — подсказать, что
// правильно, что нет, и что лучше сделать сейчас»).
//
// Пометка — служебный ход ученика: виджет шлёт её вместо вопроса и не рисует, а
// модель видит её в истории. Иначе «да» на её первое «Открыть?» пришло бы без её
// реплики: разговор обязан начинаться с ученика, и сервер срезал бы её. Как
// отвечать на пометку — в правилах (prompt.js), а не в ней самой: правила одни
// для всех и кэшируются.
//
// Отдельным модулем, а не в prompt.js: виджету нужна только пометка, а prompt.js
// тянет за собой базу знаний — в браузерный бандл ей незачем.

export const OPENING_MARK = '[ученик открыл окно]'

/** Ход «ученик открыл окно», а не вопрос, набранный учеником. */
export const isOpeningTurn = (content) => String(content ?? '').trim() === OPENING_MARK

// Состояние экрана для «один раз на экран»: Луна не повторяет первую реплику,
// если ученик закрыл и снова открыл окно, ничего не поменяв. Цифры выброшены:
// таймер записи, счёт и время плеера тикают сами, и без этого каждое открытие
// считалось бы новым экраном — и платным вызовом модели.
export function screenStateKey(screenId, snapshotText) {
  const text = String(snapshotText ?? '').replace(/\d+/g, '#').replace(/\s+/g, ' ').trim()
  let h = 5381
  for (let i = 0; i < text.length; i++) h = ((h << 5) + h + text.charCodeAt(i)) | 0
  return `${screenId || ''}|${text.length}|${(h >>> 0).toString(36)}`
}
