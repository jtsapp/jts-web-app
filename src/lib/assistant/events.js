/**
 * Указание к пометке события — рядом с ней, в последнем ходе (buildTurns).
 * @param {{type: string}} ev разобранная пометка (parseEventMark)
 * @param {'ru'|'kk'|'en'} lang язык интерфейса: проактивное сообщение — на нём (ТЗ, промт, раздел 2)
 */
export function eventHint(ev, lang = 'ru', gender = null) {
  if (!ev || !WHAT[ev.type]) return ''
  const lines = [
    'Ты пишешь первой: ученик ничего не спрашивал, сайт заметил событие.',
    WHAT[ev.type](ev),
  ]
  // Род: о прошлом ученика модель писала «ты остановилась», «ты прошла» и при указании об обращении рядом (v1: 10 из 20
  // у «вернулся после паузы»). Пол указан в Профиле — указание об обращении (turnHints.addressHint) разрешает род.
  if (lang === 'ru' && !gender) {
    lines.push('Пол ученика неизвестен: ни одного слова с родом о нём — ни в главном, ни в придаточном, ни в вопросе («ты остановилась», «то, что ты прошла», «ты открыла», «Готова?» — нельзя). Пиши через настоящее время и существительные: «пройденное», «готово», «Начнём?».')
  }
  // У «вернулся после паузы» и «перерыв окончен» план — запасной ответ: главное там экран.
  const facts = planFacts(ev)
  if (facts) lines.push(facts)
  lines.push(
    `Под ответом сайт сам поставит кнопки ${ev.type === 'return_after_gap' && ev.lite ? '«Начать» и «Вернуть обычный план»' : BUTTON_WORDS[ev.type]}: метки [[…]] не ставь и ссылки на разделы не пиши.`,
    // Знакомство и итог теста несут больше (кто ты и как устроен день; уровень, стороны, цель, шаг) — им 2–4 предложения.
    HOME_ONLY.has(ev.type)
      ? 'Коротко: 2–4 предложения, до 400 символов, без списков и заголовков; не больше одного эмодзи.'
      : 'Коротко: 1–3 предложения, до 220 символов, без списков и заголовков; не больше одного эмодзи.',
  )
  lines.push(lang === 'kk' ? `Пиши по-казахски, на «сен», без русских слов; например: ${KK_SAMPLE[ev.type]}` : LANG_LINE[lang] || LANG_LINE.ru)
  return lines.join('\n')
}

