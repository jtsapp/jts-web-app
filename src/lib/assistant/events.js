// Свежие цифры плана из пометки — модели словами: профиль мог отстать (см. шапку).
function planFacts(ev) {
  const facts = []
  if (ev.plan === 'none') return 'Плана по дням у ученика нет: не говори о шагах и минутах плана, совет — по «Совету сайта» из профиля (если он есть).'
  const only = FACTS[ev.type]
  if (only === 'none') return ''
  if (!only && ev.total) facts.push(`шагов плана на сегодня — ${ev.total}`)
  if (!only && ev.done) facts.push(`сделано — ${ev.done}${ev.dmin ? `, ${ev.dmin} мин` : ''}`)
  if (!only && ev.left) facts.push(`осталось — ${ev.left}${ev.min ? `, около ${ev.min} мин` : ''}`)
  if (ev.next && stepWord(ev.next)) facts.push(`следующий шаг — ${stepWord(ev.next)}${ev.nmin ? `, около ${ev.nmin} мин` : ''}`)
  return facts.length
    ? `Свежие цифры плана (им верь больше, чем «Плану на сегодня» в профиле — профиль мог не успеть обновиться): ${facts.join('; ')}.`
    : ''
}

