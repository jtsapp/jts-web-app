/**
 * Какие экраны кабинета преподавателю не положены.
 *
 * Сайдбар режет ему меню до TEACHER_SECTIONS (components/Sidebar.jsx), но меню
 * — это косметика, а не запрет: `?screen=` попадал в состояние без единой
 * сверки с ролью (App.jsx, эффект диплинков), и преподаватель проваливался в
 * ученический раздел, которого у него нет в навигации. Выйти оттуда можно было
 * только кнопкой «Назад» самого экрана — в меню такого пункта нет.
 *
 * Данных чужого ученика он там не видит: экраны показывают СВОЙ аккаунт, и у
 * преподавателя они попросту пустые. Это не дыра в доступе, а тупик в
 * навигации, и чинится он тем же приёмом, что уже стоит на аккаунте класса
 * (BOOTH_SCREENS в App.jsx): эффект приводит состояние в порядок, а зажим на
 * рендере не даёт чужому экрану смонтироваться даже на один кадр.
 *
 * СПИСОК ЗАКРЫТЫХ, А НЕ ОТКРЫТЫХ — и это осознанно. Собственные экраны
 * преподавателя ведут в общие: из «Уроков» — в каталог курса, тарифы и рабочее
 * пространство, из него — в словарь; а кнопка «Открыть» в админке ведёт во все
 * разделы «Практики» (reading, writing, listening, workbook). Белый список
 * пришлось бы держать длиннее, и он молча ломал бы кнопку при каждом новом
 * переходе — а поломка выглядела бы как «нажал и выкинуло на Уроки».
 */

/** Экраны, которые принадлежат ученику и преподавателю не нужны ни при каких условиях. */
export const STUDENT_ONLY_SCREENS = new Set([
  // «Обучение»: карта королевств и плеер урока — это прогресс ученика.
  'kingdom',
  'kingdom-interior',
  // Ученическая «Главная» — сводка уровня и слабых сторон. Преподавателю
  // homeScreenFor и так открывает «Уроки», сюда он попадал только по адресу.
  'home',
  // Домашняя работа ученика (сдача и ответы). Преподаватель проверяет работы
  // вкладкой внутри «Уроков» и в админке, а не этим экраном.
  'homework',
  // Тест уровня во всех видах.
  'test-intro',
  'test',
  'speaking-test',
  // IELTS-модуль.
  'ielts',
  'ielts-listening',
  'ielts-reading',
  'ielts-writing',
  'ielts-speaking',
  'ielts-progress',
  // Пакеты минут голосового тьютора: следуют за самим тьютором (tutor-*), без
  // него экран покупки ведёт в никуда.
  'minutes',
])

/**
 * Словарь НЕ закрыт намеренно, хотя по смыслу тоже ученический: в него ведёт
 * кнопка из рабочего пространства урока (`onVocab` в App.jsx), которым
 * преподаватель пользуется. Закрыть его значило бы оставить в его собственном
 * интерфейсе кнопку, которая выкидывает на «Уроки».
 *
 * Тарифы (`pricing`) тоже открыты, но их «Назад» ведёт в `kingdom` — оттуда
 * преподавателя уведёт этот же страж, на «Уроки». Это лучше, чем тупик.
 */
export function isStudentOnlyScreen(screen) {
  if (typeof screen !== 'string' || !screen) return false
  // Вся зона тьютора — префиксом, а не перечислением: экранов tutor-* два
  // десятка, они добавляются, и забытый в списке новый молча остался бы
  // открытым. Тот же приём, что у persistsInUrl в App.jsx.
  return STUDENT_ONLY_SCREENS.has(screen) || screen.startsWith('tutor-')
}
