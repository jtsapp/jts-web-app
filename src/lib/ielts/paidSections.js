// Единственный источник правды о том, какие секции IELTS тратят демо-квоту.
// Вынесен из quota.js отдельно, потому что quota.js - серверный модуль (ходит
// в auth-server.js и db/ielts.js, которые тянут за собой Neon и секреты) и
// его нельзя импортировать в клиентский экран (src/screens/IeltsPage.jsx).
// Список секций при этом должен быть ОДИН на сервер и клиент - иначе экран
// рано или поздно разъедется с бэкендом по тому, что считать платным.
//
// Speaking (Azure-распознавание + разбор моделью) и Writing (оценка моделью) -
// внешняя платная проверка, ради которой демо-лимит вообще существует.
// Reading и Listening проверяются локально по ключам ответов (key-grading.js)
// и ничего не стоят - блокировать их наравне с платными секциями означало бы
// отбирать у демо-ученика функциональность, за которую никто не платит.
const PAID_IELTS_SECTIONS = new Set(['speaking', 'writing'])

export function sectionConsumesQuota(section) {
  return PAID_IELTS_SECTIONS.has(String(section || '').toLowerCase())
}

export { PAID_IELTS_SECTIONS }
