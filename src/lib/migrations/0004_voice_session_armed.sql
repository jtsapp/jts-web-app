-- Лимит голосового тьютора начинает течь с подключения ТЬЮТОРА, а не с выдачи
-- токена. Между этими моментами ученик ждёт соединения (а при потерянном
-- room_finished — вообще уже ушёл), и минуты капали ни за что.
--
-- armed_at — момент, когда в комнату вошёл тьютор. NULL значит он ещё не
-- подключился: списывать нечего.
alter table voice_session add column if not exists armed_at timestamptz;

-- Пульс вкладки. Без него открытая сессия списывалась по настенным часам:
-- ученик закрыл разговор и ушёл читать разбор, а остаток лимита продолжал
-- таять. Теперь платное окно кончается на последнем пульсе плюс запас.
alter table voice_session add column if not exists last_seen_at timestamptz;

-- Строки, заведённые до этой миграции, оставляем на старом правиле
-- (тьютор = открытие комнаты): иначе их минуты просто исчезли бы. Пульса у них
-- нет, поэтому платное окно у таких строк сразу считается закрытым и расти
-- перестаёт — ровно то, что нужно висящему мусору.
update voice_session set armed_at = started_at where armed_at is null;

create index if not exists voice_session_device_idx on voice_session (device_id);
