-- Купленные минуты тьютора («Докупить минуты»).
--
-- Разделение то же, что и для лимитов: сколько минут КУПЛЕНО, знает бэкенд
-- (таблица tutor_minute_purchases, отдаётся в GET /mobile/aitutor/limit), а
-- сколько ПРОГОВОРЕНО — знает эта база, где и так посекундно считаются звонки.
-- Второго счётчика расхода на стороне бэкенда нет намеренно: две копии одного
-- остатка рано или поздно расходятся.
--
-- from_pool ставится в момент выдачи токена: суточный (или месячный) лимит уже
-- исчерпан, и разговор идёт за счёт купленных минут. Решение принимается один
-- раз на сессию, а не пересчитывается по ходу — иначе разговор, начатый в
-- пределах лимита, посреди фразы начал бы съедать оплаченное.
alter table voice_session add column if not exists from_pool boolean not null default false;

-- Минуты из пула НЕ попадают в seconds, и это важно: seconds — расход против
-- лимитов (суточного, месячного и пула тарифа). Сложи их вместе — и купленные
-- минуты съедали бы пул абонемента, за который человек заплатил отдельно.
alter table voice_usage add column if not exists pool_seconds integer not null default 0;
