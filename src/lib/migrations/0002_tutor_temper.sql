-- Нрав тьютора (ось 18+): второй характер у того же тьютора.
--
-- Спарк умеет быть добрым и злым, Декстер — матерящимся и спокойным; ученик
-- выбирает кнопкой «18+» на экране выбора тьютора. Значения: 'calm' | 'harsh'.
-- NULL = ученик не выбирал, берётся дефолт тьютора (см. defaultTemper в
-- src/tutor/tutors.js) — поэтому бэкфилла здесь НЕТ намеренно: у Декстера
-- дефолт теперь спокойный, и старые ученики получат спокойного, пока сами не
-- нажмут 18+. Это решение продукта, а не побочный эффект.
--
-- Персону из нрава собирает уже агент (persona_key в agent/agent.py); сюда
-- едет только сама ось, а ключ тьютора остаётся в колонке tutor.
alter table learner add column if not exists tutor_temper text;
