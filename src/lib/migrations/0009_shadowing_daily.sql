-- Лимит оценок Shadowing из недельного становится ДНЕВНЫМ.
--
-- Десять кредитов на неделю — это две оценки в день и стена к четвергу:
-- раздел, в который заходят каждый день, упирался в потолок, рассчитанный на
-- один заход. Решение владельца: те же десять, но в сутки.
--
-- Колонку переименовываем, а не оставляем «week_key» со значением-датой: имя,
-- которое врёт про содержимое, дороже одной миграции. У письма своя таблица
-- (writing_assess) и свой недельный бюджет — её не трогаем.
--
-- Старые недельные строки удаляем: их ключ ('2026-W38') ни с одним дневным не
-- совпадёт, и они остались бы мусором с бессмысленным значением. Побочный
-- эффект ровно один и он и так неизбежен при смене периода — у всех обнуляется
-- остаток на сегодня.
alter table shadowing_assess rename column week_key to day_key;

delete from shadowing_assess where day_key like '%-W%';

comment on column shadowing_assess.day_key is 'Сутки UTC, ''2026-09-18''. См. lib/db/shadowingBudget.js';
