-- Счётчик показов строки повторения без обратной связи от тьютора.
--
-- Лестницу Лейтнера двигал только log_review, а модель зовёт его почти никогда:
-- на 03.09.2026 в проде на 56 строк review_item пришёлся ОДИН вызов, и все 56
-- висели в box 0 с due_at в прошлом. Просроченное = «в промпт каждого звонка»,
-- поэтому ученик слышал одну и ту же ошибку (у одного — Past Simple с did)
-- сессия за сессией.
--
-- Теперь сам показ считается повторением: touchServedReviews увеличивает
-- serves и отодвигает due_at, а после трёх показов без ответа двигает коробку.
-- reviewItem (реальная обратная связь) сбрасывает счётчик в 0.
alter table review_item add column if not exists serves integer not null default 0;
