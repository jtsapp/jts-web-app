-- Дневной лимит разборов устного ответа в «Ситуациях» (Практика).
--
-- Один разбор = STT (Azure) + оценка произношения (Azure) + грейдер (Sonnet)
-- ≈ $0.02. Кнопка «Записать» стоит прямо под заданием, и жать её можно
-- бесконечно, поэтому потолок нужен: 20 разборов в сутки (~$0.40/день на
-- аккаунт), демо-аккаунту 5 (~$0.10) — он живёт 7–14 дней и не платит.
--
-- Единица списания — разбор, а не секунды, как у Shadowing: там оценивают
-- отрывок целиком и минута записи стоит как две, здесь ответ на задание
-- короткий и сверху ограничен длиной записи в самом роуте.
--
-- Ключ суток — дата UTC ('2026-09-20'), как у shadowing_assess: иначе вечер в
-- Алматы и вечер в Стамбуле попадают в разные сутки.
create table if not exists situations_assess (
  profile_id text        not null,
  day_key    text        not null,   -- сутки UTC, '2026-09-20'
  used       integer     not null default 0,   -- потрачено разборов
  updated_at timestamptz not null default now(),
  primary key (profile_id, day_key)
);

comment on table situations_assess is 'Дневной лимит разборов «Ситуаций». См. lib/db/situationsBudget.js';
