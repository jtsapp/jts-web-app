// Рамка — строка-шаблон с пропуском «…» («Would you mind …ing?», «I'll … to
// …», «My closest friend is … .»): студент дополняет её своим. Синтез пропуск
// прочитать не может и выдаёт кашу — «Would you mind, De Qing?», «All 2», —
// поэтому рамки синтезом не озвучиваются вовсе (решение 24.09.2026). Запись
// диктора курса, если она есть, остаётся: живой голос держит паузу на месте
// пропуска.
//
// То же правило стоит в плеере (src/learning/CourseStepPlayer.jsx, isFrame):
// рамку без записи он не читает браузерным синтезом.
const FRAME = /…|\.\.\./

const isFrame = (text) => FRAME.test(String(text ?? '').replace(/<[^>]+>/g, ''))

module.exports = { isFrame }
