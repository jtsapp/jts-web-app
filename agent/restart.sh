#!/usr/bin/env bash
# Перезапуск воркера на LiveKit Cloud + проверка, что он поднялся с нужным
# окружением.
#
# Зачем скрипт, а не одна команда: секреты агента — это переменные окружения,
# и у уже запущенного процесса они не меняются. Поменяли секрет в дашборде —
# пока воркер не перезапущен, он работает на старом значении. Глазами по логу
# этого не видно, поэтому проверку делаем здесь.
#
# `lk agent restart` перезапускает пул воркеров, НЕ обрывая активные сессии —
# этим он и отличается от `lk agent update-secrets`, которая рвёт разговоры (а
# с `--overwrite` ещё и сносит все секреты разом; см. DEPLOY.md, шаг 5.3).
#
# Код агента команда не пересобирает. Правили agent.py, персону, методичку или
# словари — нужен `lk agent deploy`, рестарта мало.
#
# Запуск из каталога agent/ (рядом лежит livekit.toml с id агента):
#   ./restart.sh
set -euo pipefail

cd "$(dirname "$0")"

if ! command -v lk >/dev/null 2>&1; then
  echo "lk не найден. Поставить: https://docs.livekit.io/home/cli/cli-setup/" >&2
  exit 1
fi

echo "== Рестарт воркера =="
lk agent restart

echo
echo "== Статус =="
lk agent status

echo
echo "== Секреты (только имена, значений LiveKit не показывает) =="
lk agent secrets

echo
echo "== Лог. Что смотреть =============================================="
echo "  'STT terms: N entries'        — воркер стартовал заново"
echo "  'Cascade STT: Soniox (...)'   — распознавание собралось"
echo "  '[brain] shim at <адрес>'     — мозг взят с ОТДЕЛЬНОГО сервера"
echo "                                  (VOICE_BRAIN_URL задан);"
echo "                                  строки нет — мозг на основном стенде"
echo "  'Error code: 502'             — мозг не отвечает, это поломка"
echo "==================================================================="
echo
# Лог стримится до Ctrl+C: строки про [brain] и STT появляются на старте
# воркера, а 502 — только когда кто-то заговорит с тьютором.
lk agent logs
