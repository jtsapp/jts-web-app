// Next отдаёт всё из /public с `Cache-Control: public, max-age=0`, а nginx перед
// ним заголовки не переписывает. На проде это значило: при каждом переходе между
// экранами браузер заново спрашивал КАЖДУЮ картинку. На 4G это 150–400 мс на
// запрос, соединение HTTP/1.1 (максимум 6 параллельных) — отсюда жалоба клиента
// «даже на 4g очень долго грузит все фотки, все экраны».
//
// Длинный max-age здесь опасен, и это не теория: в /public нет ни хэшей в
// именах, ни версий в ссылках, а файлы регулярно перезаписываются под тем же
// именем — арт королей (2760ee9), картинки итогов (0446ed0), обложки сценариев
// тьютора (89373b0), весь вывод экстракторов в /practice. Поставь месяц — и
// исправленный контент не доедет до вернувшегося пользователя вообще никак:
// браузер даже не спросит сервер, а сбросить кэш нечем.
//
// Поэтому свежесть короткая, а живёт файл в кэше долго за счёт
// stale-while-revalidate: сутки (данные — час) запросов нет вовсе, дальше файл
// отдаётся из кэша мгновенно и обновляется в фоне. Правка контента опаздывает
// максимум на один заход, а не на месяц.
const ART = 'public, max-age=86400, stale-while-revalidate=2592000'
const DATA = 'public, max-age=3600, stale-while-revalidate=86400'

const cache = (source, value) => ({ source, headers: [{ key: 'Cache-Control', value }] })

/** @type {import('next').NextConfig} */
const nextConfig = {
  // Секреты читаются серверными route-handlers через process.env — в клиент
  // уходят только NEXT_PUBLIC_*.

  // Самодостаточный `.next/standalone` (сервер + только нужные node_modules)
  // для self-host в Docker — без этого Vercel-сборка тащит весь node_modules.
  output: 'standalone',

  async headers() {
    return [
      cache('/assets/:path*', ART),
      // Медиа перенесённого курса: картинки и аудио весят 185 МБ и правятся
      // разве что вместе с самим уроком.
      cache('/course/:level/img/:path*', ART),
      cache('/course/:level/audio/:path*', ART),
      // Тьютор и Практика идут по «данным», хотя картинок там больше, чем
      // данных: под /practice лежит вывод четырёх экстракторов (books, grammar,
      // vocab, situations), который правится точечно и должен доезжать быстро,
      // а раскладывать эти две папки по расширениям — больше правил, чем пользы.
      cache('/tutor/:path*', DATA),
      cache('/practice/:path*', DATA),
      // JSON уроков «Обучения» — a1.json это 780 КБ, и он тянулся заново на
      // каждый вход в королевство. Шаги перенесённого курса лежат уровнем ниже
      // (:file — ровно один сегмент, поэтому img/ и audio/ сюда не попадают и
      // остаются на «арт»-сроке выше).
      cache('/learning/:path*', DATA),
      cache('/course/:level/:file', DATA),
    ]
  },
}

export default nextConfig
